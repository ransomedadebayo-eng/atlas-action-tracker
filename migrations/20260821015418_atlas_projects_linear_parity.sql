as $function$
begin
  insert into public.atlas_project_activity_log (project_id, event, old_value, new_value, actor)
  values (
    new.project_id,
    case
      when tg_op = 'INSERT' then 'milestone_created'
      when new.status = 'archived' and old.status <> 'archived' then 'milestone_archived'
      else 'milestone_updated'
    end,
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    to_jsonb(new),
    case when tg_op = 'INSERT' then new.created_by else new.updated_by end
  );
  return new;
end
$function$;

