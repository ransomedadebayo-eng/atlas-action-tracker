create or replace function public.post_atlas_project_update(
  p_project_id text,
  p_update_id text,
  p_health text,
  p_body text,
  p_actor text
)
returns jsonb
language plpgsql
set search_path = ''
as $function$
declare
  project_row public.atlas_projects%rowtype;
  update_row public.atlas_project_updates%rowtype;
  old_health text;
begin
  if p_health not in ('on_track', 'at_risk', 'off_track') then
    raise exception using errcode = '22023', message = 'ATLAS_PROJECT_UPDATE_HEALTH_INVALID';
  end if;
  if nullif(btrim(p_body), '') is null then
    raise exception using errcode = '22023', message = 'ATLAS_PROJECT_UPDATE_BODY_REQUIRED';
  end if;

  select * into project_row
    from public.atlas_projects
   where id = p_project_id
   for update;
  if not found then
    raise exception using errcode = 'P0002', message = 'ATLAS_PROJECT_NOT_FOUND';
  end if;
  if project_row.status = 'archived' then
    raise exception using errcode = '55000', message = 'ATLAS_PROJECT_ARCHIVED';
  end if;
  old_health := project_row.health;

  insert into public.atlas_project_updates (id, project_id, health, body, created_by)
  values (p_update_id, p_project_id, p_health, btrim(p_body), p_actor)
  returning * into update_row;

  update public.atlas_projects
     set health = p_health,
         revision = revision + 1,
         updated_by = p_actor,
         updated_at = timezone('utc', now())
   where id = p_project_id
  returning * into project_row;

  insert into public.atlas_project_activity_log (project_id, event, old_value, new_value, actor)
  values (
    p_project_id,
    'health_update_posted',
    jsonb_build_object('health', old_health),
    jsonb_build_object('update_id', p_update_id, 'health', p_health),
    p_actor
  );

  return jsonb_build_object('update', to_jsonb(update_row), 'project', to_jsonb(project_row));
end
$function$;

create or replace function public.assign_atlas_action_to_project(
  p_project_id text,
  p_action_id text,
  p_milestone_id text,
  p_estimate_points integer,
  p_actor text
)
returns jsonb
language plpgsql
set search_path = ''
as $function$
declare
  project_row public.atlas_projects%rowtype;
  action_row public.atlas_actions%rowtype;
  old_project_id text;
  old_milestone_id text;
  old_estimate integer;
begin
  select * into project_row from public.atlas_projects where id = p_project_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_PROJECT_NOT_FOUND'; end if;
  if project_row.status = 'archived' then raise exception using errcode = '55000', message = 'ATLAS_PROJECT_ARCHIVED'; end if;
  if p_estimate_points is not null and (p_estimate_points < 0 or p_estimate_points > 100000) then
    raise exception using errcode = '22023', message = 'ATLAS_PROJECT_ESTIMATE_INVALID';
  end if;
  if p_milestone_id is not null and not exists (
    select 1 from public.atlas_project_milestones
     where id = p_milestone_id and project_id = p_project_id and status <> 'archived'
  ) then
    raise exception using errcode = '23503', message = 'ATLAS_PROJECT_MILESTONE_INVALID';
  end if;

  select * into action_row from public.atlas_actions where id = p_action_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_ACTION_NOT_FOUND'; end if;
  old_project_id := action_row.project_id;
  old_milestone_id := action_row.project_milestone_id;
  old_estimate := action_row.estimate_points;

  update public.atlas_actions
     set project_id = p_project_id,
         project_milestone_id = p_milestone_id,
         estimate_points = p_estimate_points,
         updated_at = timezone('utc', now())
   where id = p_action_id
  returning * into action_row;

  insert into public.atlas_activity_log (action_id, event, old_value, new_value, actor)
  values (
    p_action_id,
    'project_assigned',
    jsonb_build_object('project_id', old_project_id, 'project_milestone_id', old_milestone_id, 'estimate_points', old_estimate)::text,
    jsonb_build_object('project_id', p_project_id, 'project_milestone_id', p_milestone_id, 'estimate_points', p_estimate_points)::text,
    p_actor
  );
  insert into public.atlas_project_activity_log (project_id, event, old_value, new_value, actor)
  values (p_project_id, 'action_assigned', jsonb_build_object('project_id', old_project_id), jsonb_build_object('action_id', p_action_id, 'milestone_id', p_milestone_id), p_actor);
  return to_jsonb(action_row);
end
$function$;

create or replace function public.remove_atlas_action_from_project(
  p_project_id text,
  p_action_id text,
  p_actor text
)
returns jsonb
language plpgsql
set search_path = ''
as $function$
declare
  action_row public.atlas_actions%rowtype;
  old_value jsonb;
begin
  select * into action_row
    from public.atlas_actions
   where id = p_action_id and project_id = p_project_id
   for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_PROJECT_ACTION_NOT_FOUND'; end if;
  old_value := jsonb_build_object('project_id', action_row.project_id, 'project_milestone_id', action_row.project_milestone_id, 'estimate_points', action_row.estimate_points);

  update public.atlas_actions
     set project_id = null,
         project_milestone_id = null,
         estimate_points = null,
         updated_at = timezone('utc', now())
   where id = p_action_id
  returning * into action_row;

  insert into public.atlas_activity_log (action_id, event, old_value, new_value, actor)
  values (p_action_id, 'project_removed', old_value::text, jsonb_build_object('project_id', null, 'project_milestone_id', null, 'estimate_points', null)::text, p_actor);
  insert into public.atlas_project_activity_log (project_id, event, old_value, new_value, actor)
  values (p_project_id, 'action_removed', jsonb_build_object('action_id', p_action_id), null, p_actor);
  return to_jsonb(action_row);
end
$function$;

