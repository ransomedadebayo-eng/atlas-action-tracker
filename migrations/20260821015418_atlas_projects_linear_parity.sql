-- Linear parity slice 1: first-class ATLAS projects, milestones, health updates,
-- dependencies, action membership, effort, and append-only project evidence.
-- Forward-only. No project or project-history row is physically deleted.

create table if not exists public.atlas_projects (
  id text primary key,
  name text not null,
  summary text not null default '',
  description text not null default '',
  business text,
  status text not null default 'planned'
    check (status in ('backlog', 'planned', 'in_progress', 'paused', 'completed', 'canceled', 'archived')),
  health text not null default 'no_update'
    check (health in ('on_track', 'at_risk', 'off_track', 'no_update')),
  priority text
    check (priority is null or priority in ('p0', 'p1', 'p2', 'p3')),
  lead_id text references public.atlas_members(id),
  members jsonb not null default '[]'::jsonb
    check (jsonb_typeof(members) = 'array'),
  start_date date,
  target_date date,
  color text,
  icon text,
  update_frequency text not null default 'weekly'
    check (update_frequency in ('weekly', 'biweekly', 'monthly', 'never')),
  archived_from_status text,
  revision bigint not null default 0 check (revision >= 0),
  created_by text not null default 'system',
  updated_by text not null default 'system',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check (start_date is null or target_date is null or start_date <= target_date)
);

create table if not exists public.atlas_project_milestones (
  id text primary key,
  project_id text not null references public.atlas_projects(id) on delete restrict,
  name text not null,
  description text not null default '',
  target_date date,
  status text not null default 'planned'
    check (status in ('planned', 'in_progress', 'completed', 'archived')),
  sort_order integer not null default 0,
  archived_from_status text,
  revision bigint not null default 0 check (revision >= 0),
  created_by text not null default 'system',
  updated_by text not null default 'system',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (project_id, name)
);

create table if not exists public.atlas_project_updates (
  id text primary key,
  project_id text not null references public.atlas_projects(id) on delete restrict,
  health text not null check (health in ('on_track', 'at_risk', 'off_track')),
  body text not null,
  created_by text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.atlas_project_dependencies (
  id text primary key,
  blocked_project_id text not null references public.atlas_projects(id) on delete restrict,
  blocking_project_id text not null references public.atlas_projects(id) on delete restrict,
  status text not null default 'active'
    check (status in ('active', 'resolved', 'archived')),
  note text not null default '',
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check (blocked_project_id <> blocking_project_id)
);

create unique index if not exists atlas_project_dependencies_active_pair_idx
  on public.atlas_project_dependencies (blocked_project_id, blocking_project_id)
  where status = 'active';

create table if not exists public.atlas_project_activity_log (
  id bigint generated by default as identity primary key,
  project_id text not null references public.atlas_projects(id) on delete restrict,
  event text not null,
  old_value jsonb,
  new_value jsonb,
  actor text not null,
  created_at timestamptz not null default timezone('utc', now())
);

