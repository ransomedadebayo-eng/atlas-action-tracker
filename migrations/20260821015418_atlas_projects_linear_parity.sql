create or replace function public.atlas_validate_project_membership()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  milestone_project_id text;
begin
  if new.project_milestone_id is not null then
    if new.project_id is null then
      raise exception using errcode = '23514', message = 'ATLAS_PROJECT_REQUIRED_FOR_MILESTONE';
    end if;

    select milestone.project_id
      into milestone_project_id
      from public.atlas_project_milestones milestone
     where milestone.id = new.project_milestone_id
       and milestone.status <> 'archived';

    if milestone_project_id is null or milestone_project_id <> new.project_id then
      raise exception using errcode = '23514', message = 'ATLAS_PROJECT_MILESTONE_MISMATCH';
    end if;
  end if;

  return new;
end
$function$;

