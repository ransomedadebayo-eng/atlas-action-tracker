create or replace function public.atlas_audit_project_row()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  event_name text;
  event_actor text;
begin
  if tg_op = 'INSERT' then
    event_name := 'created';
    event_actor := new.created_by;
    insert into public.atlas_project_activity_log (project_id, event, old_value, new_value, actor)
    values (new.id, event_name, null, to_jsonb(new), event_actor);
  else
    event_name := case
      when new.status = 'archived' and old.status <> 'archived' then 'archived'
      when old.status = 'archived' and new.status <> 'archived' then 'restored'
      when new.health is distinct from old.health then 'health_changed'
      when new.status is distinct from old.status then 'status_changed'
      else 'updated'
    end;
    event_actor := new.updated_by;
    insert into public.atlas_project_activity_log (project_id, event, old_value, new_value, actor)
    values (new.id, event_name, to_jsonb(old), to_jsonb(new), event_actor);
  end if;
  return new;
end
$function$;

create or replace function public.atlas_audit_project_milestone_row()
