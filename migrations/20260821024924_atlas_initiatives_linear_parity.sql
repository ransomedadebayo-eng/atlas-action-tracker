-- Linear parity slice 5: strategic initiatives, multi-parent hierarchy,
-- project rollups, structured updates, resources, graph inputs, and views.

create table if not exists public.atlas_initiatives (
  id text primary key,
  name text not null,
  summary text not null default '',
  description text not null default '',
  business text,
  status text not null default 'planned'
    check (status in ('proposed', 'planned', 'active', 'completed', 'canceled', 'archived')),
  health text not null default 'no_update'
    check (health in ('on_track', 'at_risk', 'off_track', 'no_update')),
  priority text check (priority is null or priority in ('p0', 'p1', 'p2', 'p3')),
  owner_id text references public.atlas_members(id),
  labels jsonb not null default '[]'::jsonb check (jsonb_typeof(labels) = 'array'),
  start_date date,
  target_date date,
  color text,
  icon text,
  update_frequency text not null default 'weekly'
    check (update_frequency in ('daily', 'weekly', 'biweekly', 'monthly', 'never')),
  sort_order numeric(30,10) not null default 0,
  completed_at timestamptz,
  archived_from_status text,
  revision bigint not null default 0 check (revision >= 0),
  created_by text not null default 'system',
  updated_by text not null default 'system',
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check (start_date is null or target_date is null or start_date <= target_date)
);

create table if not exists public.atlas_initiative_projects (
  id text primary key,
  initiative_id text not null references public.atlas_initiatives(id) on delete restrict,
  project_id text not null references public.atlas_projects(id) on delete restrict,
  status text not null default 'active' check (status in ('active', 'archived')),
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists atlas_initiative_projects_active_pair_idx
  on public.atlas_initiative_projects (initiative_id, project_id) where status = 'active';
create index if not exists atlas_initiative_projects_project_idx
  on public.atlas_initiative_projects (project_id, initiative_id) where status = 'active';

create table if not exists public.atlas_initiative_relations (
  id text primary key,
  parent_initiative_id text not null references public.atlas_initiatives(id) on delete restrict,
  child_initiative_id text not null references public.atlas_initiatives(id) on delete restrict,
  status text not null default 'active' check (status in ('active', 'archived')),
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check (parent_initiative_id <> child_initiative_id)
);

create unique index if not exists atlas_initiative_relations_active_pair_idx
  on public.atlas_initiative_relations (parent_initiative_id, child_initiative_id) where status = 'active';
create index if not exists atlas_initiative_relations_child_idx
  on public.atlas_initiative_relations (child_initiative_id, parent_initiative_id) where status = 'active';

create table if not exists public.atlas_initiative_updates (
  id text primary key,
  initiative_id text not null references public.atlas_initiatives(id) on delete restrict,
  health text not null check (health in ('on_track', 'at_risk', 'off_track')),
  body text not null,
  context_snapshot jsonb not null default '{}'::jsonb,
  created_by text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.atlas_initiative_resources (
  id text primary key,
  initiative_id text not null references public.atlas_initiatives(id) on delete restrict,
  resource_type text not null default 'link' check (resource_type in ('link', 'document')),
  title text not null,
  url text,
  document_ref text,
  status text not null default 'active' check (status in ('active', 'archived')),
  revision bigint not null default 0 check (revision >= 0),
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check (
    (resource_type = 'link' and nullif(btrim(url), '') is not null)
    or (resource_type = 'document' and nullif(btrim(document_ref), '') is not null)
  )
);

create table if not exists public.atlas_initiative_activity_log (
  id bigint generated by default as identity primary key,
  initiative_id text not null references public.atlas_initiatives(id) on delete restrict,
  event text not null,
  old_value jsonb,
  new_value jsonb,
  actor text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists atlas_initiatives_status_target_idx
  on public.atlas_initiatives (status, target_date, sort_order);
create index if not exists atlas_initiatives_owner_status_idx
  on public.atlas_initiatives (owner_id, status);
create index if not exists atlas_initiative_updates_created_idx
  on public.atlas_initiative_updates (initiative_id, created_at desc);
create index if not exists atlas_initiative_resources_active_idx
  on public.atlas_initiative_resources (initiative_id, title) where status = 'active';
create index if not exists atlas_initiative_activity_created_idx
  on public.atlas_initiative_activity_log (initiative_id, created_at desc);

create or replace function public.atlas_manage_initiative_row()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  if new.owner_id is not null and new.owner_id not in ('ransomed', 'codex', 'claude') then
    raise exception using errcode = '23514', message = 'ATLAS_INITIATIVE_OWNER_NOT_ALLOWED';
  end if;
  if new.labels is null or jsonb_typeof(new.labels) <> 'array' then
    raise exception using errcode = '23514', message = 'ATLAS_INITIATIVE_LABELS_ARRAY_REQUIRED';
  end if;
  if tg_op = 'UPDATE' then
    if new.status = 'completed' and old.status <> 'completed' then
      new.completed_at := coalesce(new.completed_at, timezone('utc', now()));
    elsif old.status = 'completed' and new.status <> 'completed' then
      new.completed_at := null;
    end if;
  elsif new.status = 'completed' then
    new.completed_at := coalesce(new.completed_at, timezone('utc', now()));
  end if;
  return new;
end
$function$;

create or replace function public.atlas_audit_initiative_row()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  insert into public.atlas_initiative_activity_log (initiative_id, event, old_value, new_value, actor)
  values (
    new.id,
    case
      when tg_op = 'INSERT' then 'initiative_created'
      when new.status = 'archived' and old.status <> 'archived' then 'initiative_archived'
      when old.status = 'archived' and new.status <> 'archived' then 'initiative_restored'
      when new.health is distinct from old.health then 'initiative_health_changed'
      when new.status is distinct from old.status then 'initiative_status_changed'
      else 'initiative_updated'
    end,
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    to_jsonb(new),
    case when tg_op = 'INSERT' then new.created_by else new.updated_by end
  );
  return new;
end
$function$;

create or replace function public.atlas_audit_initiative_child_row()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  target_initiative text;
  event_name text;
  event_actor text;
begin
  if tg_table_name = 'atlas_initiative_projects' then
    target_initiative := new.initiative_id;
    event_name := case when tg_op = 'INSERT' then 'project_attached' when new.status = 'archived' then 'project_detached' else 'project_membership_restored' end;
    event_actor := case when tg_op = 'INSERT' then new.created_by else new.updated_by end;
  elsif tg_table_name = 'atlas_initiative_relations' then
    target_initiative := new.parent_initiative_id;
    event_name := case when tg_op = 'INSERT' then 'sub_initiative_attached' when new.status = 'archived' then 'sub_initiative_detached' else 'sub_initiative_restored' end;
    event_actor := case when tg_op = 'INSERT' then new.created_by else new.updated_by end;
  else
    target_initiative := new.initiative_id;
    event_name := case when tg_op = 'INSERT' then 'resource_created' when new.status = 'archived' then 'resource_archived' else 'resource_updated' end;
    event_actor := case when tg_op = 'INSERT' then new.created_by else new.updated_by end;
  end if;
  insert into public.atlas_initiative_activity_log (initiative_id, event, old_value, new_value, actor)
  values (target_initiative, event_name, case when tg_op = 'INSERT' then null else to_jsonb(old) end, to_jsonb(new), event_actor);
  return new;
end
$function$;

