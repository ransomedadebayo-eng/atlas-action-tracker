create or replace function public.set_atlas_initiative_project(
  p_initiative_id text,
  p_project_id text,
  p_active boolean,
  p_actor text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  initiative_row public.atlas_initiatives%rowtype;
  membership_row public.atlas_initiative_projects%rowtype;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into initiative_row from public.atlas_initiatives where id = p_initiative_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_NOT_FOUND'; end if;
  if initiative_row.status = 'archived' then raise exception using errcode = '55000', message = 'ATLAS_INITIATIVE_ARCHIVED'; end if;
  if not exists (select 1 from public.atlas_projects where id = p_project_id and status <> 'archived') then
    raise exception using errcode = 'P0002', message = 'ATLAS_PROJECT_NOT_FOUND';
  end if;
  select * into membership_row from public.atlas_initiative_projects
   where initiative_id = p_initiative_id and project_id = p_project_id
   order by created_at desc limit 1 for update;
  if found then
    update public.atlas_initiative_projects set status = case when p_active then 'active' else 'archived' end,
      updated_by = p_actor, updated_at = timezone('utc', now()) where id = membership_row.id returning * into membership_row;
  elsif p_active then
    insert into public.atlas_initiative_projects (id, initiative_id, project_id, status, created_by, updated_by)
    values (gen_random_uuid()::text, p_initiative_id, p_project_id, 'active', p_actor, p_actor)
    returning * into membership_row;
  else
    raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_PROJECT_NOT_FOUND';
  end if;
  return to_jsonb(membership_row);
end
$function$;

create or replace function public.set_atlas_initiative_parent(
  p_child_initiative_id text,
  p_parent_initiative_id text,
  p_active boolean,
  p_actor text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  child_row public.atlas_initiatives%rowtype;
  parent_row public.atlas_initiatives%rowtype;
  relation_row public.atlas_initiative_relations%rowtype;
  ancestor_depth integer := 1;
  descendant_depth integer := 1;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  if p_child_initiative_id = p_parent_initiative_id then raise exception using errcode = '23514', message = 'ATLAS_INITIATIVE_SELF_PARENT'; end if;
  select * into child_row from public.atlas_initiatives where id = p_child_initiative_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_NOT_FOUND'; end if;
  select * into parent_row from public.atlas_initiatives where id = p_parent_initiative_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_PARENT_NOT_FOUND'; end if;
  if child_row.status = 'archived' or parent_row.status = 'archived' then raise exception using errcode = '55000', message = 'ATLAS_INITIATIVE_ARCHIVED'; end if;

  if p_active then
    if exists (
      with recursive descendants(id) as (
        select p_child_initiative_id
        union
        select relation.child_initiative_id from public.atlas_initiative_relations relation
        join descendants on relation.parent_initiative_id = descendants.id where relation.status = 'active'
      ) select 1 from descendants where id = p_parent_initiative_id
    ) then raise exception using errcode = '23514', message = 'ATLAS_INITIATIVE_CYCLE'; end if;

    with recursive ancestors(id, depth, path) as (
      select p_parent_initiative_id, 1, array[p_parent_initiative_id]
      union all
      select relation.parent_initiative_id, ancestors.depth + 1, ancestors.path || relation.parent_initiative_id
      from public.atlas_initiative_relations relation join ancestors on relation.child_initiative_id = ancestors.id
      where relation.status = 'active' and not relation.parent_initiative_id = any(ancestors.path)
    ) select coalesce(max(depth), 1) into ancestor_depth from ancestors;
    with recursive descendants(id, depth, path) as (
      select p_child_initiative_id, 1, array[p_child_initiative_id]
      union all
      select relation.child_initiative_id, descendants.depth + 1, descendants.path || relation.child_initiative_id
      from public.atlas_initiative_relations relation join descendants on relation.parent_initiative_id = descendants.id
      where relation.status = 'active' and not relation.child_initiative_id = any(descendants.path)
    ) select coalesce(max(depth), 1) into descendant_depth from descendants;
    if ancestor_depth + descendant_depth > 5 then raise exception using errcode = '23514', message = 'ATLAS_INITIATIVE_MAX_DEPTH'; end if;
  end if;

  select * into relation_row from public.atlas_initiative_relations
   where parent_initiative_id = p_parent_initiative_id and child_initiative_id = p_child_initiative_id
   order by created_at desc limit 1 for update;
  if found then
    update public.atlas_initiative_relations set status = case when p_active then 'active' else 'archived' end,
      updated_by = p_actor, updated_at = timezone('utc', now()) where id = relation_row.id returning * into relation_row;
  elsif p_active then
    insert into public.atlas_initiative_relations (id, parent_initiative_id, child_initiative_id, status, created_by, updated_by)
    values (gen_random_uuid()::text, p_parent_initiative_id, p_child_initiative_id, 'active', p_actor, p_actor)
    returning * into relation_row;
  else
    raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_RELATION_NOT_FOUND';
  end if;
  return to_jsonb(relation_row);
end
$function$;

create or replace function public.post_atlas_initiative_update(
  p_initiative_id text,
  p_update_id text,
  p_health text,
  p_body text,
  p_actor text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  initiative_row public.atlas_initiatives%rowtype;
  update_row public.atlas_initiative_updates%rowtype;
  snapshot jsonb;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  if p_health not in ('on_track', 'at_risk', 'off_track') then raise exception using errcode = '22023', message = 'ATLAS_INITIATIVE_UPDATE_HEALTH_INVALID'; end if;
  if nullif(btrim(p_body), '') is null then raise exception using errcode = '22023', message = 'ATLAS_INITIATIVE_UPDATE_BODY_REQUIRED'; end if;
  select * into initiative_row from public.atlas_initiatives where id = p_initiative_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_NOT_FOUND'; end if;
  if initiative_row.status = 'archived' then raise exception using errcode = '55000', message = 'ATLAS_INITIATIVE_ARCHIVED'; end if;
  with recursive tree(id) as (
    select p_initiative_id
    union
    select relation.child_initiative_id from public.atlas_initiative_relations relation
    join tree on relation.parent_initiative_id = tree.id where relation.status = 'active'
  ), projects as (
    select distinct membership.project_id from public.atlas_initiative_projects membership
    join tree on tree.id = membership.initiative_id where membership.status = 'active'
  )
  select jsonb_build_object(
    'status', initiative_row.status, 'owner_id', initiative_row.owner_id,
    'target_date', initiative_row.target_date, 'revision', initiative_row.revision,
    'projects', count(project.id),
    'project_health', jsonb_build_object(
      'on_track', count(*) filter (where project.health = 'on_track'),
      'at_risk', count(*) filter (where project.health = 'at_risk'),
      'off_track', count(*) filter (where project.health = 'off_track'),
      'no_update', count(*) filter (where project.health = 'no_update')
    )
  ) into snapshot from projects join public.atlas_projects project on project.id = projects.project_id;
  insert into public.atlas_initiative_updates (id, initiative_id, health, body, context_snapshot, created_by)
  values (p_update_id, p_initiative_id, p_health, btrim(p_body), coalesce(snapshot, '{}'::jsonb), p_actor)
  returning * into update_row;
  update public.atlas_initiatives set health = p_health, revision = revision + 1,
    updated_by = p_actor, updated_at = timezone('utc', now()) where id = p_initiative_id;
  insert into public.atlas_initiative_activity_log (initiative_id, event, new_value, actor)
  values (p_initiative_id, 'initiative_update_posted', to_jsonb(update_row), p_actor);
  return to_jsonb(update_row);
end
$function$;

create or replace function public.move_atlas_initiative_order(
  p_initiative_id text,
  p_before_initiative_id text,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  initiative_row public.atlas_initiatives%rowtype;
  target_order numeric;
  previous_order numeric;
  new_order numeric;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into initiative_row from public.atlas_initiatives where id = p_initiative_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_NOT_FOUND'; end if;
  if p_expected_revision is not null and initiative_row.revision <> p_expected_revision then raise exception using errcode = '40001', message = 'ATLAS_INITIATIVE_REVISION_CONFLICT'; end if;
  if p_before_initiative_id is null then
    select coalesce(max(sort_order), 0) + 1000 into new_order from public.atlas_initiatives where id <> p_initiative_id;
  else
    select sort_order into target_order from public.atlas_initiatives where id = p_before_initiative_id for update;
    if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_REFERENCE_NOT_FOUND'; end if;
    select max(sort_order) into previous_order from public.atlas_initiatives
      where id not in (p_initiative_id, p_before_initiative_id) and sort_order < target_order;
    new_order := case when previous_order is null then target_order - 1000 else (previous_order + target_order) / 2 end;
  end if;
  update public.atlas_initiatives set sort_order = new_order, revision = revision + 1,
    updated_by = p_actor, updated_at = timezone('utc', now()) where id = p_initiative_id returning * into initiative_row;
  return to_jsonb(initiative_row);
end
$function$;

create or replace function public.transition_atlas_initiative(
  p_initiative_id text,
  p_restore boolean,
  p_actor text,
  p_expected_revision bigint
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  initiative_row public.atlas_initiatives%rowtype;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into initiative_row from public.atlas_initiatives where id = p_initiative_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_NOT_FOUND'; end if;
  if initiative_row.revision <> p_expected_revision then raise exception using errcode = '40001', message = 'ATLAS_INITIATIVE_REVISION_CONFLICT'; end if;
  if p_restore then
    if initiative_row.status <> 'archived' then return to_jsonb(initiative_row); end if;
    update public.atlas_initiatives set status = coalesce(archived_from_status, 'planned'), archived_from_status = null,
      revision = revision + 1, updated_by = p_actor, updated_at = timezone('utc', now())
      where id = p_initiative_id returning * into initiative_row;
  else
    if initiative_row.status = 'archived' then return to_jsonb(initiative_row); end if;
    update public.atlas_initiatives set archived_from_status = status, status = 'archived',
      revision = revision + 1, updated_by = p_actor, updated_at = timezone('utc', now())
      where id = p_initiative_id returning * into initiative_row;
  end if;
  return to_jsonb(initiative_row);
end
$function$;

create or replace function public.upsert_atlas_initiative_resource(
  p_resource_id text,
  p_initiative_id text,
  p_resource_type text,
  p_title text,
  p_url text,
  p_document_ref text,
  p_status text,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  initiative_row public.atlas_initiatives%rowtype;
  resource_row public.atlas_initiative_resources%rowtype;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  if p_resource_type not in ('link', 'document') or p_status not in ('active', 'archived') then raise exception using errcode = '22023', message = 'ATLAS_INITIATIVE_RESOURCE_INVALID'; end if;
  if nullif(btrim(p_title), '') is null then raise exception using errcode = '22023', message = 'ATLAS_INITIATIVE_RESOURCE_TITLE_REQUIRED'; end if;
  select * into initiative_row from public.atlas_initiatives where id = p_initiative_id;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_NOT_FOUND'; end if;
  if initiative_row.status = 'archived' then raise exception using errcode = '55000', message = 'ATLAS_INITIATIVE_ARCHIVED'; end if;
  if p_resource_id is null then
    insert into public.atlas_initiative_resources (id, initiative_id, resource_type, title, url, document_ref, status, created_by, updated_by)
    values (gen_random_uuid()::text, p_initiative_id, p_resource_type, btrim(p_title), p_url, p_document_ref, p_status, p_actor, p_actor)
    returning * into resource_row;
  else
    select * into resource_row from public.atlas_initiative_resources where id = p_resource_id and initiative_id = p_initiative_id for update;
    if not found then raise exception using errcode = 'P0002', message = 'ATLAS_INITIATIVE_RESOURCE_NOT_FOUND'; end if;
    if p_expected_revision is null or resource_row.revision <> p_expected_revision then raise exception using errcode = '40001', message = 'ATLAS_INITIATIVE_RESOURCE_REVISION_CONFLICT'; end if;
