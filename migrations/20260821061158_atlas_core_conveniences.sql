create or replace function public.start_atlas_cycle_today(
  p_cycle_id text,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  cycle_row public.atlas_cycles%rowtype;
  active_row public.atlas_cycles%rowtype;
  schedule_row public.atlas_cycle_schedules%rowtype;
  result jsonb;
  server_timestamp timestamptz := timezone('utc',now());
begin
  if p_actor<>'ransomed' then raise exception using errcode='42501',message='ATLAS_OWNER_REQUIRED'; end if;
  select * into cycle_row from public.atlas_cycles where id=p_cycle_id for update;
  if not found then raise exception using errcode='P0002',message='ATLAS_CYCLE_NOT_FOUND'; end if;
  if cycle_row.status<>'planned' then raise exception using errcode='55000',message='ATLAS_CYCLE_NOT_PLANNED'; end if;
  if p_expected_revision is not null and cycle_row.revision<>p_expected_revision then raise exception using errcode='40001',message='ATLAS_CYCLE_REVISION_CONFLICT'; end if;
  select * into schedule_row from public.atlas_cycle_schedules where id=cycle_row.schedule_id for update;
  if exists(select 1 from public.atlas_cycles earlier where earlier.schedule_id=cycle_row.schedule_id and earlier.status='planned' and earlier.start_date<cycle_row.start_date) then
    raise exception using errcode='55000',message='ATLAS_NEXT_PLANNED_CYCLE_REQUIRED';
  end if;
  select * into active_row from public.atlas_cycles where schedule_id=cycle_row.schedule_id and status='active' limit 1 for update;
  if active_row.id is not null then
    return public.complete_atlas_cycle(active_row.id,p_actor,active_row.revision,true);
  end if;
  update public.atlas_cycles
     set start_date=current_date,end_date=current_date+(schedule_row.duration_weeks*7-1),status='active',
         revision=revision+1,updated_by=p_actor,updated_at=server_timestamp
   where id=p_cycle_id returning * into cycle_row;
  with future as(
    select id,row_number() over(order by cycle_number)::integer as position
      from public.atlas_cycles where schedule_id=cycle_row.schedule_id and status='planned'
  )
  update public.atlas_cycles future_cycle
     set start_date=cycle_row.end_date+schedule_row.cooldown_days+1+((future.position-1)*(schedule_row.duration_weeks*7+schedule_row.cooldown_days)),
         end_date=cycle_row.end_date+schedule_row.cooldown_days+((future.position-1)*(schedule_row.duration_weeks*7+schedule_row.cooldown_days))+schedule_row.duration_weeks*7,
         revision=future_cycle.revision+1,updated_by=p_actor,updated_at=server_timestamp
    from future where future_cycle.id=future.id;
  insert into public.atlas_cycle_activity_log(cycle_id,schedule_id,event,new_value,actor,created_at)
  values(cycle_row.id,cycle_row.schedule_id,'cycle_started_today',to_jsonb(cycle_row),p_actor,server_timestamp);
  return jsonb_build_object('cycle',to_jsonb(cycle_row),'started_today',true);
end
$function$;

