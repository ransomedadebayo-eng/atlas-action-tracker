create or replace function public.atlas_sync_text_references()
returns trigger
language plpgsql
set search_path=''
as $function$
declare
  source_type_value text := tg_argv[0];
  source_id_value text;
  field_name text;
  field_value text;
  combined_value text := '';
  captured_number bigint;
  target_row public.atlas_actions%rowtype;
  relation_row public.atlas_action_relations%rowtype;
  canonical_source text;
  canonical_target text;
  source_active boolean := true;
  server_timestamp timestamptz := timezone('utc',now());
begin
  source_id_value := to_jsonb(new)->>'id';
  if to_jsonb(new) ? 'status' then source_active := coalesce(to_jsonb(new)->>'status','active') <> 'archived'; end if;
  foreach field_name in array tg_argv[1:array_length(tg_argv,1)] loop
    field_value := coalesce(to_jsonb(new)->>field_name,'');
    combined_value := combined_value || E'\n' || field_value;
  end loop;

  update public.atlas_text_references
     set status='stale',revision=revision+1,last_seen_at=server_timestamp
   where source_type=source_type_value and source_id=source_id_value and status='active';

  if source_active then
    for captured_number in
      select distinct captures[1]::bigint
        from regexp_matches(combined_value,'(?i)(?:@)?ATLAS-([0-9]+)','g') captures
    loop
      select * into target_row from public.atlas_actions where display_number=captured_number;
      if target_row.id is null or (source_type_value='action' and target_row.id=source_id_value) then continue; end if;
      field_name := case
        when position(lower(target_row.identifier) in lower(coalesce(to_jsonb(new)->>'title',''))) > 0 then 'title'
        when position(lower(target_row.identifier) in lower(coalesce(to_jsonb(new)->>'description',''))) > 0 then 'description'
        when position(lower(target_row.identifier) in lower(coalesce(to_jsonb(new)->>'notes',''))) > 0 then 'notes'
        when position(lower(target_row.identifier) in lower(coalesce(to_jsonb(new)->>'summary',''))) > 0 then 'summary'
        when position(lower(target_row.identifier) in lower(coalesce(to_jsonb(new)->>'content',''))) > 0 then 'content'
        else tg_argv[1]
      end;
      insert into public.atlas_text_references(id,source_type,source_id,source_field,target_action_id,matched_identifier,status)
      values(gen_random_uuid()::text,source_type_value,source_id_value,field_name,target_row.id,target_row.identifier,'active')
      on conflict(source_type,source_id,source_field,target_action_id) do update
        set status='active',revision=public.atlas_text_references.revision+1,last_seen_at=server_timestamp,
            matched_identifier=excluded.matched_identifier;

      if source_type_value='action' then
        canonical_source := least(source_id_value,target_row.id);
        canonical_target := greatest(source_id_value,target_row.id);
        update public.atlas_action_relations
           set status='active',revision=revision+1,updated_by='system',updated_at=server_timestamp
         where source_action_id=canonical_source and target_action_id=canonical_target
           and relation_type='related' and note='auto:text_reference' and status<>'active'
           and not exists(
             select 1 from public.atlas_action_relations active_relation
              where active_relation.source_action_id=canonical_source and active_relation.target_action_id=canonical_target
                and active_relation.relation_type='related' and active_relation.status='active'
           );
        if not found then
          insert into public.atlas_action_relations(id,source_action_id,target_action_id,relation_type,status,note,created_by,updated_by)
          values(gen_random_uuid()::text,canonical_source,canonical_target,'related','active','auto:text_reference','system','system')
          on conflict do nothing;
        end if;
      end if;
    end loop;
  end if;

  if source_type_value='action' then
    for relation_row in
      select * from public.atlas_action_relations
       where note='auto:text_reference' and relation_type='related' and status='active'
         and source_id_value in (source_action_id,target_action_id)
    loop
      if not exists(
        select 1 from public.atlas_text_references reference
         where reference.source_type='action' and reference.status='active'
           and ((reference.source_id=relation_row.source_action_id and reference.target_action_id=relation_row.target_action_id)
             or (reference.source_id=relation_row.target_action_id and reference.target_action_id=relation_row.source_action_id))
      ) then
        update public.atlas_action_relations set status='archived',revision=revision+1,updated_by='system',updated_at=server_timestamp
         where id=relation_row.id;
      end if;
    end loop;
  end if;
  return new;
end
$function$;

