declare role_name text;
begin
  foreach role_name in array array['anon','authenticated'] loop
    if exists(select 1 from pg_roles where rolname=role_name) then
      execute format('revoke execute on function public.convert_atlas_action_to_project(text,text,text,text,bigint) from %I',role_name);
      execute format('revoke execute on function public.start_atlas_cycle_today(text,text,bigint) from %I',role_name);
    end if;
  end loop;
  if exists(select 1 from pg_roles where rolname='service_role') then
    grant execute on function public.convert_atlas_action_to_project(text,text,text,text,bigint) to service_role;
    grant execute on function public.start_atlas_cycle_today(text,text,bigint) to service_role;
  end if;
end
