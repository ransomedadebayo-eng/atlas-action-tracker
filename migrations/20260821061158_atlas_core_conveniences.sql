create or replace function public.convert_atlas_action_to_project(
  p_action_id text,
  p_project_id text,
  p_project_name text,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  action_row public.atlas_actions%rowtype;
  project_row public.atlas_projects%rowtype;
  conversion_row public.atlas_action_project_conversions%rowtype;
  child_ids jsonb;
  source_snapshot jsonb;
  resolved_name text;
  server_timestamp timestamptz := timezone('utc', now());
begin
  if p_actor <> 'ransomed' then raise exception using errcode='42501',message='ATLAS_OWNER_REQUIRED'; end if;
  select * into action_row from public.atlas_actions where id=p_action_id for update;
  if not found then raise exception using errcode='P0002',message='ATLAS_ACTION_NOT_FOUND'; end if;
  if action_row.status='archived' then raise exception using errcode='55000',message='ATLAS_ACTION_ARCHIVED'; end if;
  if p_expected_revision is not null and action_row.revision<>p_expected_revision then raise exception using errcode='40001',message='ATLAS_REVISION_CONFLICT'; end if;
  source_snapshot := to_jsonb(action_row);
  if not exists(select 1 from public.atlas_actions where parent_action_id=p_action_id) then
    raise exception using errcode='55000',message='ATLAS_PARENT_ACTION_REQUIRED';
  end if;
  if exists(select 1 from public.atlas_action_project_conversions where source_action_id=p_action_id) then
    select * into conversion_row from public.atlas_action_project_conversions where source_action_id=p_action_id;
    select * into project_row from public.atlas_projects where id=conversion_row.project_id;
    return jsonb_build_object('project',to_jsonb(project_row),'conversion',to_jsonb(conversion_row),'idempotent',true);
  end if;

  perform 1 from public.atlas_actions where parent_action_id=p_action_id order by id for update;
  select coalesce(jsonb_agg(id order by id),'[]'::jsonb) into child_ids
    from public.atlas_actions where parent_action_id=p_action_id;
  resolved_name := coalesce(nullif(btrim(p_project_name),''),action_row.title);

  insert into public.atlas_projects(
    id,name,summary,description,business,status,health,priority,lead_id,members,
    start_date,target_date,update_frequency,created_by,updated_by,created_at,updated_at
  ) values(
    p_project_id,resolved_name,left(coalesce(action_row.description,''),500),coalesce(action_row.description,''),
    action_row.business,'planned','no_update',action_row.priority,
    case when coalesce(action_row.owners,'[]'::jsonb) ? 'ransomed' then 'ransomed' else null end,
    coalesce(action_row.owners,'[]'::jsonb),current_date,
    case when action_row.due_date ~ '^\d{4}-\d{2}-\d{2}$' then action_row.due_date::date else null end,
    'weekly',p_actor,p_actor,server_timestamp,server_timestamp
  ) returning * into project_row;

  update public.atlas_actions
     set project_id=p_project_id,project_milestone_id=null,parent_action_id=null,
         updated_at=server_timestamp
   where parent_action_id=p_action_id;

  update public.atlas_actions
     set title=left(action_row.title || ' (project issue)',500),project_id=p_project_id,
         project_milestone_id=null,parent_action_id=null,revision=revision+1,updated_at=server_timestamp
   where id=p_action_id returning * into action_row;

  insert into public.atlas_action_project_conversions(
    id,source_action_id,project_id,source_action_snapshot,child_action_ids,actor,created_at
  ) values(gen_random_uuid()::text,p_action_id,p_project_id,source_snapshot,child_ids,p_actor,server_timestamp)
  returning * into conversion_row;

  insert into public.atlas_project_activity_log(project_id,event,new_value,actor,created_at)
  values(p_project_id,'created_from_parent_action',jsonb_build_object('source_action_id',p_action_id,'child_action_ids',child_ids),p_actor,server_timestamp);
  insert into public.atlas_activity_log(action_id,event,new_value,actor,created_at)
  values(p_action_id,'converted_to_project',p_project_id,p_actor,server_timestamp);
  return jsonb_build_object('project',to_jsonb(project_row),'action',to_jsonb(action_row),'conversion',to_jsonb(conversion_row),'idempotent',false);
end
$function$;

