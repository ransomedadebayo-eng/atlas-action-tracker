create or replace function public.atlas_apply_hierarchy_completion_policy()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  workflow_row public.atlas_workflows%rowtype;
  parent_row public.atlas_actions%rowtype;
  child_id text;
  server_timestamp timestamptz := timezone('utc', now());
begin
  if new.status not in ('done','completed','closed')
     or old.status in ('done','completed','closed') then
    return new;
  end if;

  select * into workflow_row
    from public.atlas_workflows
   where archived_at is null
     and (business is not distinct from new.business or business is null)
   order by (business is not distinct from new.business) desc, created_at
   limit 1;

  if workflow_row.id is null then return new; end if;

  if workflow_row.parent_auto_close and new.parent_action_id is not null then
    update public.atlas_actions parent
       set status = 'done', resolution = 'completed', revision = parent.revision + 1,
           evidence_json = jsonb_build_object(
             'version', 2, 'kind', 'hierarchy_automation',
             'summary', 'Completed automatically after all direct sub-actions completed.',
             'source_action_id', new.id,
             'verification', jsonb_build_object('status', 'system_recorded')
           ),
           updated_at = server_timestamp
     where parent.id = new.parent_action_id
       and parent.status not in ('done','completed','closed','archived','cancelled','canceled')
       and coalesce(parent.work_mode, 'autonomous') <> 'user_only'
       and coalesce(parent.approval_state, 'not_required') not in ('needs_review','deferred')
       and exists (select 1 from public.atlas_actions child where child.parent_action_id = parent.id)
       and not exists (
         select 1 from public.atlas_actions child
          where child.parent_action_id = parent.id
            and child.status not in ('done','completed','closed','archived','cancelled','canceled')
       )
     returning parent.* into parent_row;
    if parent_row.id is not null then
      insert into public.atlas_hierarchy_automation_events(workflow_id,source_action_id,affected_action_id,event)
      values(workflow_row.id,new.id,parent_row.id,'parent_auto_closed');
      insert into public.atlas_activity_log(action_id,event,new_value,actor,created_at)
      values(parent_row.id,'parent_auto_closed',new.id,'system',server_timestamp);
    end if;
  end if;

  if workflow_row.sub_action_auto_close then
    for child_id in
      update public.atlas_actions child
         set status = 'done', resolution = 'completed', revision = child.revision + 1,
             evidence_json = jsonb_build_object(
               'version', 2, 'kind', 'hierarchy_automation',
               'summary', 'Completed automatically with the parent action.',
               'source_action_id', new.id,
               'verification', jsonb_build_object('status', 'system_recorded')
             ),
             updated_at = server_timestamp
       where child.parent_action_id = new.id
         and child.status not in ('done','completed','closed','archived','cancelled','canceled')
         and coalesce(child.work_mode, 'autonomous') <> 'user_only'
         and coalesce(child.approval_state, 'not_required') not in ('needs_review','deferred')
       returning child.id
    loop
      insert into public.atlas_hierarchy_automation_events(workflow_id,source_action_id,affected_action_id,event)
      values(workflow_row.id,new.id,child_id,'sub_action_auto_closed');
      insert into public.atlas_activity_log(action_id,event,new_value,actor,created_at)
      values(child_id,'sub_action_auto_closed',new.id,'system',server_timestamp);
    end loop;
  end if;
  return new;
end
$function$;

