create or replace function public.atlas_audit_saved_view_row()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  insert into public.atlas_saved_view_activity_log (view_id, event, old_value, new_value, actor)
  values (
    new.id,
    case
      when tg_op = 'INSERT' then 'view_created'
      when new.archived_at is not null and old.archived_at is null then 'view_archived'
      when new.archived_at is null and old.archived_at is not null then 'view_restored'
      when new.is_favorite is distinct from old.is_favorite then 'view_favorite_changed'
      else 'view_updated'
    end,
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    to_jsonb(new),
    case when tg_op = 'INSERT' then new.created_by else new.updated_by end
  );
  return new;
end
$function$;

