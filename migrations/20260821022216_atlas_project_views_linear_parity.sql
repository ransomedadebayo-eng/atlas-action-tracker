-- completion windows, and dependency-aware timeline movement.

alter table public.atlas_projects
  add column if not exists sort_order numeric(30,10) not null default 0,
  add column if not exists completed_at timestamptz;

with ranked as (
  select id, row_number() over (
    order by case priority when 'p0' then 0 when 'p1' then 1 when 'p2' then 2 when 'p3' then 3 else 4 end,
             created_at, id
  ) * 1000 as rank_value
  from public.atlas_projects
)
update public.atlas_projects project
set sort_order = ranked.rank_value
from ranked
where project.id = ranked.id and project.sort_order = 0;

update public.atlas_projects
set completed_at = coalesce(completed_at, updated_at)
where status = 'completed' and completed_at is null;

create or replace function public.atlas_manage_project_completion_timestamp()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  if new.status = 'completed' and old.status <> 'completed' then
    new.completed_at := coalesce(new.completed_at, timezone('utc', now()));
  elsif old.status = 'completed' and new.status <> 'completed' then
    new.completed_at := null;
  end if;
  return new;
end
$function$;

revoke all on function public.atlas_manage_project_completion_timestamp() from public;
drop trigger if exists atlas_projects_manage_completed_at on public.atlas_projects;
create trigger atlas_projects_manage_completed_at
before update of status on public.atlas_projects
for each row execute function public.atlas_manage_project_completion_timestamp();

