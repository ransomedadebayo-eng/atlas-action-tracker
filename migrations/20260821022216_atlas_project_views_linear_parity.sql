create or replace function public.move_atlas_project_order(
  p_project_id text,
  p_before_project_id text,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  project_row public.atlas_projects%rowtype;
  target_order numeric;
  previous_order numeric;
  new_order numeric;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into project_row from public.atlas_projects where id = p_project_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_PROJECT_NOT_FOUND'; end if;
  if p_expected_revision is not null and project_row.revision <> p_expected_revision then raise exception using errcode = '40001', message = 'ATLAS_PROJECT_REVISION_CONFLICT'; end if;
  if p_before_project_id is null then
    select coalesce(max(sort_order), 0) + 1000 into new_order from public.atlas_projects where id <> p_project_id;
  else
    select sort_order into target_order from public.atlas_projects where id = p_before_project_id for update;
    if not found then raise exception using errcode = 'P0002', message = 'ATLAS_PROJECT_REFERENCE_NOT_FOUND'; end if;
    select max(sort_order) into previous_order from public.atlas_projects
     where id not in (p_project_id, p_before_project_id) and sort_order < target_order;
    new_order := case when previous_order is null then target_order - 1000 else (previous_order + target_order) / 2 end;
  end if;
  update public.atlas_projects set sort_order = new_order, revision = revision + 1,
    updated_by = p_actor, updated_at = timezone('utc', now())
  where id = p_project_id returning * into project_row;
  return to_jsonb(project_row);
end
$function$;

create or replace function public.move_atlas_project_timeline(
  p_project_id text,
  p_start_date date,
  p_target_date date,
  p_shift_dependency_chain boolean,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  project_row public.atlas_projects%rowtype;
  delta_days integer := 0;
  moved_ids jsonb := '[]'::jsonb;
  dependent record;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  if p_start_date is not null and p_target_date is not null and p_start_date > p_target_date then raise exception using errcode = '22023', message = 'ATLAS_PROJECT_TIMEFRAME_INVALID'; end if;
  select * into project_row from public.atlas_projects where id = p_project_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_PROJECT_NOT_FOUND'; end if;
  if project_row.status = 'archived' then raise exception using errcode = '55000', message = 'ATLAS_PROJECT_ARCHIVED'; end if;
  if p_expected_revision is not null and project_row.revision <> p_expected_revision then raise exception using errcode = '40001', message = 'ATLAS_PROJECT_REVISION_CONFLICT'; end if;
  if project_row.start_date is not null and p_start_date is not null then delta_days := p_start_date - project_row.start_date; end if;
  update public.atlas_projects set start_date = p_start_date, target_date = p_target_date,
    revision = revision + 1, updated_by = p_actor, updated_at = timezone('utc', now())
  where id = p_project_id returning * into project_row;
  moved_ids := moved_ids || to_jsonb(project_row.id);

  if p_shift_dependency_chain and delta_days <> 0 then
    for dependent in
      with recursive chain(project_id) as (
        select dependency.blocked_project_id
        from public.atlas_project_dependencies dependency
        where dependency.blocking_project_id = p_project_id and dependency.status = 'active'
        union
        select dependency.blocked_project_id
        from public.atlas_project_dependencies dependency
        join chain on dependency.blocking_project_id = chain.project_id
        where dependency.status = 'active'
      )
      select project.id from public.atlas_projects project
      join chain on chain.project_id = project.id
      where project.status in ('backlog', 'planned')
      for update
    loop
      update public.atlas_projects set
        start_date = case when start_date is null then null else start_date + delta_days end,
        target_date = case when target_date is null then null else target_date + delta_days end,
        revision = revision + 1, updated_by = p_actor, updated_at = timezone('utc', now())
      where id = dependent.id;
      moved_ids := moved_ids || to_jsonb(dependent.id);
    end loop;
  end if;
  return jsonb_build_object('project', to_jsonb(project_row), 'moved_project_ids', moved_ids, 'delta_days', delta_days);
end
$function$;

