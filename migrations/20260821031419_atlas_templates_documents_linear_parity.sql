create or replace function public.instantiate_atlas_template(
  p_template_id text,
  p_title_override text,
  p_business text,
  p_context_type text,
  p_context_id text,
  p_form_values jsonb,
  p_overrides jsonb,
  p_actor text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  template_row public.atlas_templates%rowtype;
  instance_id text := gen_random_uuid()::text;
  result_id text := gen_random_uuid()::text;
  config jsonb;
  values_json jsonb := coalesce(p_form_values,'{}'::jsonb);
  field jsonb;
  field_value jsonb;
  resolved_title text;
  resolved_description text;
  resolved_priority text;
  resolved_due_date text;
  resolved_tags jsonb;
  resolved_business text;
  node jsonb;
  node_ids jsonb := '{}'::jsonb;
  milestone jsonb;
  milestone_ids jsonb := '{}'::jsonb;
  initiative_id jsonb;
  node_id text;
  parent_id text;
  milestone_id text;
  node_depth integer;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  if jsonb_typeof(values_json) <> 'object' or jsonb_typeof(coalesce(p_overrides,'{}'::jsonb)) <> 'object' then raise exception using errcode='22023',message='ATLAS_TEMPLATE_INPUT_OBJECT_REQUIRED'; end if;
  select * into template_row from public.atlas_templates where id=p_template_id for update;
  if not found then raise exception using errcode='P0002',message='ATLAS_TEMPLATE_NOT_FOUND'; end if;
  if template_row.status <> 'active' then raise exception using errcode='55000',message='ATLAS_TEMPLATE_ARCHIVED'; end if;
  config := template_row.blueprint || coalesce(p_overrides,'{}'::jsonb);

  for field in select value from jsonb_array_elements(template_row.form_schema)
  loop
    field_value := values_json->(field->>'key');
    if coalesce((field->>'required')::boolean,false) and (field_value is null or field_value='null'::jsonb or field_value='""'::jsonb or field_value='[]'::jsonb) then
      raise exception using errcode='22023',message='ATLAS_TEMPLATE_REQUIRED_FIELD_MISSING',detail=field->>'key';
    end if;
    if field->>'type' in ('dropdown','checkboxes') and field_value is not null and field_value <> 'null'::jsonb then
      if field->>'type'='dropdown' and not (field->'options' @> jsonb_build_array(field_value)) then raise exception using errcode='22023',message='ATLAS_TEMPLATE_FIELD_OPTION_INVALID',detail=field->>'key'; end if;
      if field->>'type'='checkboxes' and exists (select 1 from jsonb_array_elements(field_value) choice where not (field->'options' @> jsonb_build_array(choice))) then raise exception using errcode='22023',message='ATLAS_TEMPLATE_FIELD_OPTION_INVALID',detail=field->>'key'; end if;
    end if;
  end loop;

  insert into public.atlas_template_instances (id,template_id,template_revision,result_entity_type,result_entity_id,form_values,overrides,actor)
  values (instance_id,template_row.id,template_row.revision,template_row.template_type,result_id,values_json,coalesce(p_overrides,'{}'::jsonb),p_actor);

  if template_row.template_type='action' then
    resolved_title := coalesce(nullif(btrim(p_title_override),''),nullif(btrim(values_json->>'title'),''),nullif(btrim(config->>'title'),''));
    resolved_description := coalesce(config->>'description','');
    resolved_priority := coalesce(values_json->>'priority',config->>'priority','p2');
    resolved_due_date := coalesce(values_json->>'due_date',nullif(config->>'due_date',''),case when config ? 'due_offset_days' then (current_date + (config->>'due_offset_days')::integer)::text else null end);
    resolved_tags := coalesce(values_json->'labels',config->'tags','[]'::jsonb);
    resolved_business := coalesce(nullif(p_business,''),nullif(config->>'business',''),template_row.business);
    for field in select value from jsonb_array_elements(template_row.form_schema)
    loop
      field_value := values_json->(field->>'key');
      if field->>'type'='title' and field_value is not null then resolved_title := field_value#>>'{}';
      elsif field->>'type'='priority' and field_value is not null then resolved_priority := field_value#>>'{}';
      elsif field->>'type'='due_date' and field_value is not null then resolved_due_date := field_value#>>'{}';
      elsif field->>'type'='labels' and field_value is not null then resolved_tags := field_value;
      elsif field->>'type'='instructions' then resolved_description := resolved_description || E'\n\n' || coalesce(field->>'help_text',field->>'label','');
      elsif field_value is not null and field_value <> 'null'::jsonb and field->>'type' in ('text','long_text','dropdown','checkboxes','date') then
        resolved_description := resolved_description || E'\n\n## ' || coalesce(field->>'label',field->>'key') || E'\n' || case when jsonb_typeof(field_value)='string' then field_value#>>'{}' else field_value::text end;
      end if;
    end loop;
    if resolved_title is null then raise exception using errcode='22023',message='ATLAS_TEMPLATE_ACTION_TITLE_REQUIRED'; end if;
    if resolved_business is null then raise exception using errcode='22023',message='ATLAS_TEMPLATE_ACTION_BUSINESS_REQUIRED'; end if;
    insert into public.atlas_actions (id,title,description,status,business,priority,due_date,owners,tags,evidence_json,source_label,project_id,project_milestone_id,estimate_points,work_mode,next_action,definition_of_done,review_date,recurrence,notes,template_id,template_instance_id,created_at,updated_at)
    values (result_id,resolved_title,resolved_description,coalesce(config->>'status','not_started'),resolved_business,resolved_priority,resolved_due_date,coalesce(config->'owners','["ransomed"]'::jsonb),resolved_tags,'{}'::jsonb,'template:'||template_row.name,nullif(config->>'project_id',''),nullif(config->>'project_milestone_id',''),(config->>'estimate_points')::integer,nullif(config->>'work_mode',''),nullif(config->>'next_action',''),nullif(config->>'definition_of_done',''),nullif(config->>'review_date',''),coalesce(config->>'recurrence','none'),coalesce(config->>'notes',''),template_row.id,instance_id,timezone('utc',now()),timezone('utc',now()));

    for node,node_depth in
      with recursive nodes as (
        select value item from jsonb_array_elements(coalesce(config->'sub_actions','[]'::jsonb))
      ), walk(item,depth) as (
        select item,1 from nodes where nullif(item->>'parent_key','') is null
        union all select node.item,walk.depth+1 from nodes node join walk on node.item->>'parent_key'=walk.item->>'key'
      ) select item,depth from walk order by depth,item->>'key'
    loop
      node_id := gen_random_uuid()::text;
      node_ids := node_ids || jsonb_build_object(node->>'key',node_id);
      parent_id := case when nullif(node->>'parent_key','') is null then result_id else node_ids->>(node->>'parent_key') end;
      insert into public.atlas_actions (id,title,description,status,business,priority,due_date,owners,tags,evidence_json,source_label,parent_action_id,estimate_points,template_id,template_instance_id,created_at,updated_at)
      values (node_id,node->>'title',coalesce(node->>'description',''),coalesce(node->>'status',config->>'status','not_started'),resolved_business,coalesce(node->>'priority',resolved_priority),case when node ? 'due_offset_days' then (current_date+(node->>'due_offset_days')::integer)::text else resolved_due_date end,coalesce(node->'owners',config->'owners','["ransomed"]'::jsonb),coalesce(node->'tags','[]'::jsonb),'{}'::jsonb,'template:'||template_row.name,parent_id,(node->>'estimate_points')::integer,template_row.id,instance_id,timezone('utc',now()),timezone('utc',now()));
    end loop;

  elsif template_row.template_type='project' then
    resolved_title := coalesce(nullif(btrim(p_title_override),''),nullif(btrim(config->>'name'),''));
    resolved_business := coalesce(nullif(p_business,''),nullif(config->>'business',''),template_row.business);
    insert into public.atlas_projects (id,name,summary,description,business,status,health,priority,lead_id,members,start_date,target_date,update_frequency,template_id,template_instance_id,created_by,updated_by)
    values (result_id,resolved_title,coalesce(config->>'summary',''),coalesce(config->>'description',''),resolved_business,coalesce(config->>'status','planned'),coalesce(config->>'health','no_update'),nullif(config->>'priority',''),coalesce(nullif(config->>'lead_id',''),'ransomed'),coalesce(config->'members','["ransomed"]'::jsonb),case when nullif(config->>'start_date','') is not null then (config->>'start_date')::date when config ? 'start_offset_days' then current_date+(config->>'start_offset_days')::integer else null end,case when nullif(config->>'target_date','') is not null then (config->>'target_date')::date when config ? 'target_offset_days' then current_date+(config->>'target_offset_days')::integer else null end,coalesce(config->>'update_frequency','weekly'),template_row.id,instance_id,p_actor,p_actor);
    for milestone in select value from jsonb_array_elements(coalesce(config->'milestones','[]'::jsonb))
    loop
      milestone_id := gen_random_uuid()::text;
      milestone_ids := milestone_ids || jsonb_build_object(milestone->>'key',milestone_id);
      insert into public.atlas_project_milestones (id,project_id,name,description,target_date,status,sort_order,created_by,updated_by)
      values (milestone_id,result_id,milestone->>'name',coalesce(milestone->>'description',''),case when milestone ? 'target_offset_days' then current_date+(milestone->>'target_offset_days')::integer else null end,coalesce(milestone->>'status','planned'),coalesce((milestone->>'sort_order')::integer,0),p_actor,p_actor);
    end loop;
    for initiative_id in select value from jsonb_array_elements(coalesce(config->'initiative_ids','[]'::jsonb))
    loop
      perform public.set_atlas_initiative_project(initiative_id#>>'{}',result_id,true,p_actor);
    end loop;
    for node,node_depth in
      with recursive nodes as (select value item from jsonb_array_elements(coalesce(config->'actions','[]'::jsonb))), walk(item,depth) as (
        select item,1 from nodes where nullif(item->>'parent_key','') is null
        union all select node.item,walk.depth+1 from nodes node join walk on node.item->>'parent_key'=walk.item->>'key'
      ) select item,depth from walk order by depth,item->>'key'
    loop
      node_id := gen_random_uuid()::text;
      node_ids := node_ids || jsonb_build_object(node->>'key',node_id);
      parent_id := case when nullif(node->>'parent_key','') is null then null else node_ids->>(node->>'parent_key') end;
      milestone_id := case when nullif(node->>'milestone_key','') is null then null else milestone_ids->>(node->>'milestone_key') end;
      if nullif(node->>'milestone_key','') is not null and milestone_id is null then raise exception using errcode='22023',message='ATLAS_TEMPLATE_MILESTONE_KEY_NOT_FOUND'; end if;
      insert into public.atlas_actions (id,title,description,status,business,priority,due_date,owners,tags,evidence_json,source_label,project_id,project_milestone_id,parent_action_id,estimate_points,template_id,template_instance_id,created_at,updated_at)
      values (node_id,node->>'title',coalesce(node->>'description',''),coalesce(node->>'status','not_started'),coalesce(resolved_business,'personal'),coalesce(node->>'priority','p2'),case when node ? 'due_offset_days' then (current_date+(node->>'due_offset_days')::integer)::text else null end,coalesce(node->'owners','["ransomed"]'::jsonb),coalesce(node->'tags','[]'::jsonb),'{}'::jsonb,'template:'||template_row.name,result_id,milestone_id,parent_id,(node->>'estimate_points')::integer,template_row.id,instance_id,timezone('utc',now()),timezone('utc',now()));
    end loop;

  else
    if p_context_type is not null and p_context_type not in ('workspace','project','initiative','action','cycle') then raise exception using errcode='22023',message='ATLAS_DOCUMENT_CONTEXT_INVALID'; end if;
    if config ? 'allowed_context_types' and not (config->'allowed_context_types' @> jsonb_build_array(coalesce(p_context_type,'workspace'))) then raise exception using errcode='22023',message='ATLAS_DOCUMENT_TEMPLATE_CONTEXT_NOT_ALLOWED'; end if;
    insert into public.atlas_documents (id,title,content,context_type,context_id,icon,color,template_id,template_instance_id,status,revision,created_by,updated_by)
    values (result_id,coalesce(nullif(btrim(p_title_override),''),config->>'title'),coalesce(config->>'content',''),coalesce(p_context_type,'workspace'),case when coalesce(p_context_type,'workspace')='workspace' then null else p_context_id end,config->>'icon',config->>'color',template_row.id,instance_id,'active',0,p_actor,p_actor);
  end if;

  update public.atlas_templates set usage_count=usage_count+1,last_used_at=timezone('utc',now()),updated_at=timezone('utc',now()) where id=template_row.id;
  insert into public.atlas_template_activity_log (template_id,event,new_value,actor)
  values (template_row.id,'template_instantiated',jsonb_build_object('instance_id',instance_id,'result_entity_type',template_row.template_type,'result_entity_id',result_id,'template_revision',template_row.revision),p_actor);
  return jsonb_build_object('instance_id',instance_id,'template_id',template_row.id,'template_revision',template_row.revision,'result_entity_type',template_row.template_type,'result_entity_id',result_id);
end
$function$;

create or replace function public.transition_atlas_template(p_template_id text,p_restore boolean,p_actor text,p_expected_revision bigint)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare row_value public.atlas_templates%rowtype;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into row_value from public.atlas_templates where id=p_template_id for update;
  if not found then raise exception using errcode='P0002',message='ATLAS_TEMPLATE_NOT_FOUND'; end if;
  if row_value.revision<>p_expected_revision then raise exception using errcode='40001',message='ATLAS_TEMPLATE_REVISION_CONFLICT'; end if;
  update public.atlas_templates set status=case when p_restore then 'active' else 'archived' end,is_default=case when p_restore then is_default else false end,archived_at=case when p_restore then null else timezone('utc',now()) end,revision=revision+1,updated_by=p_actor,updated_at=timezone('utc',now()) where id=p_template_id returning * into row_value;
  return to_jsonb(row_value);
end $function$;

