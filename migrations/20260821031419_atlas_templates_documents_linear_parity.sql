-- Linear parity slice 6: action/project/document templates, structured forms,
-- transactional instantiation, provenance, defaults, and versioned documents.

create table if not exists public.atlas_templates (
  id text primary key,
  name text not null,
  description text not null default '',
  template_type text not null check (template_type in ('action', 'project', 'document')),
  mode text not null default 'standard' check (mode in ('standard', 'form')),
  scope text not null default 'workspace' check (scope in ('workspace', 'business')),
  business text,
  default_audience text not null default 'owner' check (default_audience in ('owner', 'intake', 'all')),
  is_default boolean not null default false,
  blueprint jsonb not null default '{}'::jsonb check (jsonb_typeof(blueprint) = 'object'),
  form_schema jsonb not null default '[]'::jsonb check (jsonb_typeof(form_schema) = 'array'),
  status text not null default 'active' check (status in ('active', 'archived')),
  revision bigint not null default 0 check (revision >= 0),
  usage_count bigint not null default 0 check (usage_count >= 0),
  last_used_at timestamptz,
  archived_at timestamptz,
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check ((scope = 'workspace' and business is null) or (scope = 'business' and nullif(btrim(business), '') is not null)),
  check (mode <> 'form' or template_type = 'action')
);

create unique index if not exists atlas_templates_one_default_idx
  on public.atlas_templates (template_type, coalesce(business, '__workspace__'), default_audience)
  where is_default and status = 'active';
create index if not exists atlas_templates_active_type_idx
  on public.atlas_templates (template_type, scope, business, name) where status = 'active';

create table if not exists public.atlas_template_instances (
  id text primary key,
  template_id text not null references public.atlas_templates(id) on delete restrict,
  template_revision bigint not null,
  result_entity_type text not null check (result_entity_type in ('action', 'project', 'document')),
  result_entity_id text not null,
  form_values jsonb not null default '{}'::jsonb check (jsonb_typeof(form_values) = 'object'),
  overrides jsonb not null default '{}'::jsonb check (jsonb_typeof(overrides) = 'object'),
  actor text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists atlas_template_instances_template_created_idx
  on public.atlas_template_instances (template_id, created_at desc);
create unique index if not exists atlas_template_instances_result_idx
  on public.atlas_template_instances (result_entity_type, result_entity_id);

create table if not exists public.atlas_template_activity_log (
  id bigint generated by default as identity primary key,
  template_id text not null references public.atlas_templates(id) on delete restrict,
  event text not null,
  old_value jsonb,
  new_value jsonb,
  actor text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists atlas_template_activity_created_idx
  on public.atlas_template_activity_log (template_id, created_at desc);

create table if not exists public.atlas_documents (
  id text primary key,
  title text not null,
  content text not null default '',
  context_type text not null default 'workspace'
    check (context_type in ('workspace', 'project', 'initiative', 'action', 'cycle')),
  context_id text,
  icon text,
  color text,
  template_id text references public.atlas_templates(id) on delete restrict,
  template_instance_id text references public.atlas_template_instances(id) on delete restrict,
  status text not null default 'active' check (status in ('active', 'archived')),
  revision bigint not null default 0 check (revision >= 0),
  archived_at timestamptz,
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  check ((context_type = 'workspace' and context_id is null) or (context_type <> 'workspace' and nullif(btrim(context_id), '') is not null))
);

create index if not exists atlas_documents_context_idx
