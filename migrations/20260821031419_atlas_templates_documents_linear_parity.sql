create or replace function public.atlas_validate_template_row()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  field jsonb;
  field_key text;
  field_type text;
  keys text[] := array[]::text[];
  node_count integer;
  reachable_count integer;
  max_depth integer;
begin
  if new.mode = 'form' and jsonb_array_length(new.form_schema) = 0 then
    raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_FORM_SCHEMA_REQUIRED';
  end if;
  for field in select value from jsonb_array_elements(new.form_schema)
  loop
    if jsonb_typeof(field) <> 'object' then raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_FORM_FIELD_OBJECT_REQUIRED'; end if;
    field_key := nullif(btrim(field->>'key'), '');
    field_type := field->>'type';
    if field_key is null or field_key = any(keys) then raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_FORM_FIELD_KEY_INVALID'; end if;
    if field_type not in ('text','long_text','dropdown','checkboxes','date','instructions','title','priority','due_date','labels') then
      raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_FORM_FIELD_TYPE_INVALID';
    end if;
    if field_type in ('dropdown','checkboxes') and (jsonb_typeof(field->'options') <> 'array' or jsonb_array_length(field->'options') = 0) then
      raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_FORM_FIELD_OPTIONS_REQUIRED';
    end if;
    keys := array_append(keys, field_key);
  end loop;

  if new.template_type = 'action' then
    if new.mode = 'standard' and nullif(btrim(new.blueprint->>'title'), '') is null then raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_ACTION_TITLE_REQUIRED'; end if;
    with recursive nodes as (
      select item->>'key' as key, nullif(item->>'parent_key','') as parent_key
      from jsonb_array_elements(coalesce(new.blueprint->'sub_actions','[]'::jsonb)) item
    ), walk(key, depth, path) as (
      select key, 1, array[key] from nodes where parent_key is null
      union all
      select node.key, walk.depth + 1, walk.path || node.key from nodes node join walk on node.parent_key = walk.key where not node.key = any(walk.path)
    )
    select (select count(*) from nodes), count(distinct key), coalesce(max(depth),0) into node_count, reachable_count, max_depth from walk;
  elsif new.template_type = 'project' then
    if nullif(btrim(new.blueprint->>'name'), '') is null then raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_PROJECT_NAME_REQUIRED'; end if;
    with recursive nodes as (
      select item->>'key' as key, nullif(item->>'parent_key','') as parent_key
      from jsonb_array_elements(coalesce(new.blueprint->'actions','[]'::jsonb)) item
    ), walk(key, depth, path) as (
      select key, 1, array[key] from nodes where parent_key is null
      union all
      select node.key, walk.depth + 1, walk.path || node.key from nodes node join walk on node.parent_key = walk.key where not node.key = any(walk.path)
    )
    select (select count(*) from nodes), count(distinct key), coalesce(max(depth),0) into node_count, reachable_count, max_depth from walk;
  else
    if nullif(btrim(new.blueprint->>'title'), '') is null then raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_DOCUMENT_TITLE_REQUIRED'; end if;
    node_count := 0; reachable_count := 0; max_depth := 0;
  end if;
  if node_count <> reachable_count then raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_NODE_GRAPH_INVALID'; end if;
  if max_depth > 5 then raise exception using errcode = '23514', message = 'ATLAS_TEMPLATE_NODE_MAX_DEPTH'; end if;
  return new;
end
$function$;

create or replace function public.atlas_validate_document_context()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  if new.context_type = 'workspace' then return new; end if;
  if new.context_type = 'project' and not exists (select 1 from public.atlas_projects where id = new.context_id and status <> 'archived') then raise exception using errcode = '23503', message = 'ATLAS_DOCUMENT_PROJECT_NOT_FOUND'; end if;
  if new.context_type = 'initiative' and not exists (select 1 from public.atlas_initiatives where id = new.context_id and status <> 'archived') then raise exception using errcode = '23503', message = 'ATLAS_DOCUMENT_INITIATIVE_NOT_FOUND'; end if;
  if new.context_type = 'action' and not exists (select 1 from public.atlas_actions where id = new.context_id and status <> 'archived') then raise exception using errcode = '23503', message = 'ATLAS_DOCUMENT_ACTION_NOT_FOUND'; end if;
  if new.context_type = 'cycle' and not exists (select 1 from public.atlas_cycles where id = new.context_id and status <> 'archived') then raise exception using errcode = '23503', message = 'ATLAS_DOCUMENT_CYCLE_NOT_FOUND'; end if;
  return new;
end
$function$;

create or replace function public.atlas_audit_template_row()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  insert into public.atlas_template_activity_log (template_id,event,old_value,new_value,actor)
  values (new.id,
    case when tg_op='INSERT' then 'template_created' when new.status='archived' and old.status='active' then 'template_archived' when new.status='active' and old.status='archived' then 'template_restored' when new.is_default is distinct from old.is_default then 'template_default_changed' else 'template_updated' end,
    case when tg_op='INSERT' then null else to_jsonb(old) end, to_jsonb(new), case when tg_op='INSERT' then new.created_by else new.updated_by end);
  return new;
end
$function$;

