begin
  insert into public.atlas_document_versions (document_id,revision,title,content,actor)
  values (new.id,new.revision,new.title,new.content,case when tg_op='INSERT' then new.created_by else new.updated_by end);
  insert into public.atlas_document_activity_log (document_id,event,old_value,new_value,actor)
  values (new.id,
    case when tg_op='INSERT' then 'document_created' when new.status='archived' and old.status='active' then 'document_archived' when new.status='active' and old.status='archived' then 'document_restored' else 'document_updated' end,
    case when tg_op='INSERT' then null else to_jsonb(old) end,to_jsonb(new),case when tg_op='INSERT' then new.created_by else new.updated_by end);
