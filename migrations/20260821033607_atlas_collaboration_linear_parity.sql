-- Linear parity slice 7: comments, one-level threads, selected resolutions,
-- reactions, link attachments, inline anchors, mentions, and subscriptions.

create table if not exists public.atlas_comments (
  id text primary key,
  target_type text not null check (target_type in ('action','project','initiative','document','project_update','initiative_update')),
  target_id text not null,
  parent_comment_id text references public.atlas_comments(id) on delete restrict,
  thread_root_id text references public.atlas_comments(id) on delete restrict,
  body text not null,
  mentions jsonb not null default '[]'::jsonb check (jsonb_typeof(mentions)='array'),
  attachments jsonb not null default '[]'::jsonb check (jsonb_typeof(attachments)='array'),
  anchor jsonb check (anchor is null or jsonb_typeof(anchor)='object'),
  status text not null default 'active' check (status in ('active','archived')),
  resolved_at timestamptz,
  resolved_by text,
  resolution_comment_id text references public.atlas_comments(id) on delete restrict,
  revision bigint not null default 0 check (revision>=0),
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc',now()),
  updated_at timestamptz not null default timezone('utc',now()),
  check ((parent_comment_id is null and thread_root_id is null) or (parent_comment_id is not null and thread_root_id is not null and parent_comment_id=thread_root_id))
);

create index if not exists atlas_comments_target_created_idx on public.atlas_comments(target_type,target_id,created_at);
create index if not exists atlas_comments_thread_idx on public.atlas_comments(thread_root_id,created_at) where thread_root_id is not null;
create index if not exists atlas_comments_parent_idx on public.atlas_comments(parent_comment_id) where parent_comment_id is not null;
create index if not exists atlas_comments_resolution_idx on public.atlas_comments(resolution_comment_id) where resolution_comment_id is not null;
create index if not exists atlas_comments_mentions_idx on public.atlas_comments using gin(mentions);

create table if not exists public.atlas_reactions (
  id text primary key,
  target_type text not null check (target_type in ('action','project','initiative','document','project_update','initiative_update','comment')),
  target_id text not null,
  emoji text not null,
  actor text not null,
  status text not null default 'active' check (status in ('active','removed')),
  created_at timestamptz not null default timezone('utc',now()),
  updated_at timestamptz not null default timezone('utc',now()),
  check (char_length(emoji) between 1 and 32)
);

create unique index if not exists atlas_reactions_active_actor_idx
  on public.atlas_reactions(target_type,target_id,emoji,actor) where status='active';
create index if not exists atlas_reactions_target_idx
  on public.atlas_reactions(target_type,target_id,status,emoji);

create table if not exists public.atlas_discussion_subscriptions (
  id text primary key,
  target_type text not null check (target_type in ('action','project','initiative','document','project_update','initiative_update')),
  target_id text not null,
  principal_id text not null,
  status text not null default 'active' check (status in ('active','muted')),
  created_at timestamptz not null default timezone('utc',now()),
  updated_at timestamptz not null default timezone('utc',now()),
  unique(target_type,target_id,principal_id)
);

create index if not exists atlas_discussion_subscriptions_principal_idx
  on public.atlas_discussion_subscriptions(principal_id,status,updated_at desc);

create table if not exists public.atlas_collaboration_activity_log (
  id bigint generated by default as identity primary key,
  entity_type text not null,
  entity_id text not null,
  event text not null,
  old_value jsonb,
  new_value jsonb,
  actor text not null,
  created_at timestamptz not null default timezone('utc',now())
);

create index if not exists atlas_collaboration_activity_entity_idx
  on public.atlas_collaboration_activity_log(entity_type,entity_id,created_at desc);

create or replace function public.atlas_discussion_target_exists(p_target_type text,p_target_id text)
returns boolean language plpgsql stable set search_path='' as $function$
begin
  return case p_target_type
    when 'action' then exists(select 1 from public.atlas_actions where id=p_target_id)
    when 'project' then exists(select 1 from public.atlas_projects where id=p_target_id)
    when 'initiative' then exists(select 1 from public.atlas_initiatives where id=p_target_id)
    when 'document' then exists(select 1 from public.atlas_documents where id=p_target_id)
    when 'project_update' then exists(select 1 from public.atlas_project_updates where id=p_target_id)
    when 'initiative_update' then exists(select 1 from public.atlas_initiative_updates where id=p_target_id)
    when 'comment' then exists(select 1 from public.atlas_comments where id=p_target_id)
    else false end;
end $function$;

create or replace function public.atlas_validate_comment_row()
returns trigger language plpgsql set search_path='' as $function$
declare item jsonb; principal_count integer; unique_count integer; root_row public.atlas_comments%rowtype; resolution_row public.atlas_comments%rowtype;
begin
  if not public.atlas_discussion_target_exists(new.target_type,new.target_id) then raise exception using errcode='23503',message='ATLAS_COMMENT_TARGET_NOT_FOUND'; end if;
  if nullif(btrim(new.body),'') is null then raise exception using errcode='23514',message='ATLAS_COMMENT_BODY_REQUIRED'; end if;
  select count(*),count(distinct value) into principal_count,unique_count from jsonb_array_elements_text(new.mentions);
  if principal_count<>unique_count or exists(select 1 from jsonb_array_elements_text(new.mentions) mention where mention.value not in ('ransomed','codex','claude')) then raise exception using errcode='23514',message='ATLAS_COMMENT_MENTION_INVALID'; end if;
  for item in select value from jsonb_array_elements(new.attachments) loop
    if jsonb_typeof(item)<>'object' or nullif(btrim(item->>'title'),'') is null or coalesce(item->>'url','') !~ '^https://[^[:space:]]+$' or (item ? 'size_bytes' and ((item->>'size_bytes')::bigint<0)) then raise exception using errcode='23514',message='ATLAS_COMMENT_ATTACHMENT_INVALID'; end if;
  end loop;
  if new.anchor is not null then
    if nullif(btrim(new.anchor->>'field'),'') is null or nullif(new.anchor->>'quote','') is null then raise exception using errcode='23514',message='ATLAS_COMMENT_ANCHOR_INVALID'; end if;
    if new.anchor ? 'start' and (new.anchor->>'start')::integer<0 then raise exception using errcode='23514',message='ATLAS_COMMENT_ANCHOR_INVALID'; end if;
    if new.anchor ? 'end' and (new.anchor->>'end')::integer<coalesce((new.anchor->>'start')::integer,0) then raise exception using errcode='23514',message='ATLAS_COMMENT_ANCHOR_INVALID'; end if;
  end if;
  if new.parent_comment_id is not null then
    select * into root_row from public.atlas_comments where id=new.thread_root_id;
    if not found or root_row.parent_comment_id is not null or root_row.target_type<>new.target_type or root_row.target_id<>new.target_id then raise exception using errcode='23514',message='ATLAS_COMMENT_THREAD_INVALID'; end if;
  end if;
  if new.resolution_comment_id is not null then
    if new.parent_comment_id is not null then raise exception using errcode='23514',message='ATLAS_COMMENT_REPLY_CANNOT_RESOLVE'; end if;
    select * into resolution_row from public.atlas_comments where id=new.resolution_comment_id;
    if not found or resolution_row.status<>'active' or not (resolution_row.id=new.id or resolution_row.thread_root_id=new.id) then raise exception using errcode='23514',message='ATLAS_COMMENT_RESOLUTION_INVALID'; end if;
  end if;
  return new;
end $function$;

create or replace function public.atlas_validate_reaction_row()
returns trigger language plpgsql set search_path='' as $function$
begin
  if new.actor not in ('ransomed','codex','claude') then raise exception using errcode='23514',message='ATLAS_REACTION_ACTOR_INVALID'; end if;
  if not public.atlas_discussion_target_exists(new.target_type,new.target_id) then raise exception using errcode='23503',message='ATLAS_REACTION_TARGET_NOT_FOUND'; end if;
  if new.emoji ~ '[[:space:]]' then raise exception using errcode='23514',message='ATLAS_REACTION_EMOJI_INVALID'; end if;
  return new;
end $function$;

create or replace function public.atlas_validate_subscription_row()
returns trigger language plpgsql set search_path='' as $function$
begin
  if new.principal_id not in ('ransomed','codex','claude') then raise exception using errcode='23514',message='ATLAS_SUBSCRIPTION_PRINCIPAL_INVALID'; end if;
  if not public.atlas_discussion_target_exists(new.target_type,new.target_id) then raise exception using errcode='23503',message='ATLAS_SUBSCRIPTION_TARGET_NOT_FOUND'; end if;
  return new;
end $function$;

create or replace function public.atlas_audit_collaboration_row()
returns trigger language plpgsql set search_path='' as $function$
declare kind text; row_id text; actor_value text; event_name text; new_json jsonb:=to_jsonb(new); old_json jsonb:=case when tg_op='INSERT' then null else to_jsonb(old) end;
begin
  kind:=case tg_table_name when 'atlas_comments' then 'comment' when 'atlas_reactions' then 'reaction' else 'subscription' end;
  row_id:=new_json->>'id';
  actor_value:=case when tg_table_name='atlas_comments' then case when tg_op='INSERT' then new_json->>'created_by' else new_json->>'updated_by' end when tg_table_name='atlas_reactions' then new_json->>'actor' else new_json->>'principal_id' end;
  event_name:=case when tg_op='INSERT' then kind||'_created' when tg_table_name='atlas_comments' and (new_json->>'resolved_at') is distinct from (old_json->>'resolved_at') then case when new_json->>'resolved_at' is null then 'thread_reopened' else 'thread_resolved' end when (new_json->>'status') is distinct from (old_json->>'status') then kind||'_'||(new_json->>'status') else kind||'_updated' end;
  insert into public.atlas_collaboration_activity_log(entity_type,entity_id,event,old_value,new_value,actor)
  values(kind,row_id,event_name,old_json,new_json,actor_value);
  return new;
end $function$;

