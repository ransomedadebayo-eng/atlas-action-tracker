create or replace function public.create_atlas_comment(p_target_type text,p_target_id text,p_parent_comment_id text,p_body text,p_mentions jsonb,p_attachments jsonb,p_anchor jsonb,p_actor text)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare parent_row public.atlas_comments%rowtype; root_id text; comment_row public.atlas_comments%rowtype; mention text;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  if p_parent_comment_id is not null then
    select * into parent_row from public.atlas_comments where id=p_parent_comment_id and status='active';
    if not found then raise exception using errcode='P0002',message='ATLAS_COMMENT_PARENT_NOT_FOUND'; end if;
    if parent_row.target_type<>p_target_type or parent_row.target_id<>p_target_id then raise exception using errcode='23514',message='ATLAS_COMMENT_PARENT_TARGET_MISMATCH'; end if;
    root_id:=coalesce(parent_row.thread_root_id,parent_row.id);
  end if;
  insert into public.atlas_comments(id,target_type,target_id,parent_comment_id,thread_root_id,body,mentions,attachments,anchor,status,created_by,updated_by)
  values(gen_random_uuid()::text,p_target_type,p_target_id,root_id,root_id,btrim(p_body),coalesce(p_mentions,'[]'::jsonb),coalesce(p_attachments,'[]'::jsonb),p_anchor,'active',p_actor,p_actor) returning * into comment_row;
  insert into public.atlas_discussion_subscriptions(id,target_type,target_id,principal_id,status)
  values(gen_random_uuid()::text,p_target_type,p_target_id,p_actor,'active') on conflict(target_type,target_id,principal_id) do update set status='active',updated_at=timezone('utc',now());
  for mention in select value from jsonb_array_elements_text(coalesce(p_mentions,'[]'::jsonb)) loop
    insert into public.atlas_discussion_subscriptions(id,target_type,target_id,principal_id,status)
    values(gen_random_uuid()::text,p_target_type,p_target_id,mention,'active') on conflict(target_type,target_id,principal_id) do update set status='active',updated_at=timezone('utc',now());
  end loop;
  return to_jsonb(comment_row);
end $function$;

create or replace function public.update_atlas_comment(p_comment_id text,p_body text,p_mentions jsonb,p_attachments jsonb,p_actor text,p_expected_revision bigint)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare row_value public.atlas_comments%rowtype;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into row_value from public.atlas_comments where id=p_comment_id for update;
  if not found then raise exception using errcode='P0002',message='ATLAS_COMMENT_NOT_FOUND'; end if;
  if row_value.created_by<>p_actor and p_actor<>'ransomed' then raise exception using errcode='42501',message='ATLAS_COMMENT_AUTHOR_REQUIRED'; end if;
  if row_value.status='archived' then raise exception using errcode='55000',message='ATLAS_COMMENT_ARCHIVED'; end if;
  if row_value.revision<>p_expected_revision then raise exception using errcode='40001',message='ATLAS_COMMENT_REVISION_CONFLICT'; end if;
  update public.atlas_comments set body=btrim(p_body),mentions=coalesce(p_mentions,'[]'::jsonb),attachments=coalesce(p_attachments,'[]'::jsonb),revision=revision+1,updated_by=p_actor,updated_at=timezone('utc',now()) where id=p_comment_id returning * into row_value;
  return to_jsonb(row_value);
end $function$;

create or replace function public.transition_atlas_comment(p_comment_id text,p_restore boolean,p_actor text,p_expected_revision bigint)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare row_value public.atlas_comments%rowtype;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into row_value from public.atlas_comments where id=p_comment_id for update;
  if not found then raise exception using errcode='P0002',message='ATLAS_COMMENT_NOT_FOUND'; end if;
  if row_value.created_by<>p_actor and p_actor<>'ransomed' then raise exception using errcode='42501',message='ATLAS_COMMENT_AUTHOR_REQUIRED'; end if;
  if row_value.revision<>p_expected_revision then raise exception using errcode='40001',message='ATLAS_COMMENT_REVISION_CONFLICT'; end if;
  if not p_restore and exists(select 1 from public.atlas_comments root where root.resolution_comment_id=row_value.id and root.resolved_at is not null) then raise exception using errcode='55000',message='ATLAS_COMMENT_IS_THREAD_RESOLUTION'; end if;
  update public.atlas_comments set status=case when p_restore then 'active' else 'archived' end,revision=revision+1,updated_by=p_actor,updated_at=timezone('utc',now()) where id=p_comment_id returning * into row_value;
  return to_jsonb(row_value);
end $function$;

create or replace function public.resolve_atlas_comment_thread(p_root_comment_id text,p_resolution_comment_id text,p_resolved boolean,p_actor text,p_expected_revision bigint)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare root_row public.atlas_comments%rowtype; resolution_row public.atlas_comments%rowtype;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into root_row from public.atlas_comments where id=p_root_comment_id for update;
  if not found or root_row.parent_comment_id is not null then raise exception using errcode='P0002',message='ATLAS_COMMENT_ROOT_NOT_FOUND'; end if;
  if root_row.status='archived' then raise exception using errcode='55000',message='ATLAS_COMMENT_ARCHIVED'; end if;
  if root_row.revision<>p_expected_revision then raise exception using errcode='40001',message='ATLAS_COMMENT_REVISION_CONFLICT'; end if;
  if p_resolved then
    select * into resolution_row from public.atlas_comments where id=coalesce(p_resolution_comment_id,p_root_comment_id) and status='active';
    if not found or not (resolution_row.id=root_row.id or resolution_row.thread_root_id=root_row.id) then raise exception using errcode='23514',message='ATLAS_COMMENT_RESOLUTION_INVALID'; end if;
  end if;
  update public.atlas_comments set resolved_at=case when p_resolved then timezone('utc',now()) else null end,resolved_by=case when p_resolved then p_actor else null end,resolution_comment_id=case when p_resolved then resolution_row.id else null end,revision=revision+1,updated_by=p_actor,updated_at=timezone('utc',now()) where id=root_row.id returning * into root_row;
  return to_jsonb(root_row);
end $function$;

create or replace function public.toggle_atlas_reaction(p_target_type text,p_target_id text,p_emoji text,p_actor text)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare reaction_row public.atlas_reactions%rowtype;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into reaction_row from public.atlas_reactions where target_type=p_target_type and target_id=p_target_id and emoji=p_emoji and actor=p_actor order by updated_at desc limit 1 for update;
  if found then
    update public.atlas_reactions set status=case when status='active' then 'removed' else 'active' end,updated_at=timezone('utc',now()) where id=reaction_row.id returning * into reaction_row;
  else
    insert into public.atlas_reactions(id,target_type,target_id,emoji,actor,status) values(gen_random_uuid()::text,p_target_type,p_target_id,p_emoji,p_actor,'active') returning * into reaction_row;
  end if;
  return to_jsonb(reaction_row);
end $function$;

create or replace function public.set_atlas_discussion_subscription(p_target_type text,p_target_id text,p_status text,p_actor text)
returns jsonb language plpgsql security definer set search_path='' as $function$
declare row_value public.atlas_discussion_subscriptions%rowtype;
begin
  if p_actor not in ('ransomed','codex','claude') then raise exception using errcode='22023',message='ATLAS_ACTOR_NOT_ALLOWED'; end if;
  if p_status not in ('active','muted') then raise exception using errcode='22023',message='ATLAS_SUBSCRIPTION_STATUS_INVALID'; end if;
  insert into public.atlas_discussion_subscriptions(id,target_type,target_id,principal_id,status)
  values(gen_random_uuid()::text,p_target_type,p_target_id,p_actor,p_status)
  on conflict(target_type,target_id,principal_id) do update set status=excluded.status,updated_at=timezone('utc',now()) returning * into row_value;
  return to_jsonb(row_value);
end $function$;

