create or replace function public.atlas_capture_cycle_scope(
  p_cycle_id text,
  p_event_type text,
  p_action_id text,
  p_actor text
)
returns void
language plpgsql
set search_path = ''
as $function$
declare
  unestimated_value integer := 1;
  cycle_status text;
  scope_effort integer;
  started_effort integer;
  completed_effort integer;
  issue_count integer;
  completed_count integer;
begin
  select status into cycle_status from public.atlas_cycles where id = p_cycle_id;
  if cycle_status not in ('planned', 'active') then return; end if;
  select coalesce((value->>'unestimated_value')::integer, 1)
    into unestimated_value
    from public.atlas_config where key = 'estimate_settings';
  unestimated_value := coalesce(unestimated_value, 1);

  select
    coalesce(sum(coalesce(action.estimate_points, unestimated_value)), 0)::integer,
    coalesce(sum(case when action.status in ('in_progress', 'waiting', 'blocked') then coalesce(action.estimate_points, unestimated_value) else 0 end), 0)::integer,
    coalesce(sum(case when action.status in ('done', 'completed', 'closed') then coalesce(action.estimate_points, unestimated_value) else 0 end), 0)::integer,
    count(*)::integer,
    count(*) filter (where action.status in ('done', 'completed', 'closed'))::integer
  into scope_effort, started_effort, completed_effort, issue_count, completed_count
  from public.atlas_actions action where action.cycle_id = p_cycle_id;

  insert into public.atlas_cycle_scope_events (
    cycle_id, event_type, action_id, scope_effort, started_effort,
    completed_effort, issue_count, completed_count, actor
  ) values (
    p_cycle_id, p_event_type, p_action_id, scope_effort, started_effort,
    completed_effort, issue_count, completed_count, p_actor
  );
end
$function$;

create or replace function public.atlas_capture_action_cycle_change()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  if tg_op = 'UPDATE' and old.cycle_id is not null and old.cycle_id is distinct from new.cycle_id then
    perform public.atlas_capture_cycle_scope(old.cycle_id, 'scope_removed', new.id, 'system');
  end if;
  if new.cycle_id is not null then
    perform public.atlas_capture_cycle_scope(
      new.cycle_id,
      case
        when tg_op = 'INSERT' or old.cycle_id is distinct from new.cycle_id then 'scope_added'
        when old.status is distinct from new.status then 'status_changed'
        else 'estimate_changed'
      end,
      new.id,
      'system'
    );
  end if;
  return new;
end
$function$;

revoke all on function public.atlas_capture_cycle_scope(text, text, text, text) from public;
revoke all on function public.atlas_capture_action_cycle_change() from public;

drop trigger if exists atlas_actions_capture_cycle_scope on public.atlas_actions;
create trigger atlas_actions_capture_cycle_scope
after insert or update of cycle_id, status, estimate_points on public.atlas_actions
for each row execute function public.atlas_capture_action_cycle_change();

create or replace function public.configure_atlas_cycle_schedule(
  p_schedule_id text,
  p_business text,
  p_duration_weeks integer,
  p_cooldown_days integer,
  p_future_cycles integer,
  p_start_date date,
  p_timezone text,
  p_auto_rollover boolean,
  p_auto_add_started boolean,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  schedule_row public.atlas_cycle_schedules%rowtype;
  active_row public.atlas_cycles%rowtype;
  cycle_row public.atlas_cycles%rowtype;
  next_start date;
  next_end date;
  next_number integer;
  cycle_status text;
  generated jsonb := '[]'::jsonb;
  index_value integer;
  server_timestamp timestamptz := timezone('utc', now());
begin
  if p_actor <> 'ransomed' then raise exception using errcode = '42501', message = 'ATLAS_OWNER_REQUIRED'; end if;
  if p_duration_weeks not between 1 and 8 then raise exception using errcode = '22023', message = 'ATLAS_CYCLE_DURATION_INVALID'; end if;
  if p_cooldown_days not in (0, 7, 14) then raise exception using errcode = '22023', message = 'ATLAS_CYCLE_COOLDOWN_INVALID'; end if;
  if p_future_cycles not between 1 and 15 then raise exception using errcode = '22023', message = 'ATLAS_CYCLE_FUTURE_COUNT_INVALID'; end if;
  if p_start_date is null then raise exception using errcode = '22023', message = 'ATLAS_CYCLE_START_REQUIRED'; end if;

  select * into schedule_row from public.atlas_cycle_schedules where id = p_schedule_id for update;
  if found then
    if p_expected_revision is not null and schedule_row.revision <> p_expected_revision then
      raise exception using errcode = '40001', message = 'ATLAS_CYCLE_REVISION_CONFLICT';
    end if;
    update public.atlas_cycle_schedules set
      business = p_business, enabled = true, duration_weeks = p_duration_weeks,
      cooldown_days = p_cooldown_days, future_cycles = p_future_cycles,
      start_date = p_start_date, timezone = coalesce(nullif(p_timezone, ''), 'America/Los_Angeles'),
      auto_rollover = p_auto_rollover, auto_add_started = p_auto_add_started,
      revision = revision + 1, updated_by = p_actor, updated_at = server_timestamp
    where id = p_schedule_id returning * into schedule_row;
    update public.atlas_cycles set status = 'archived', revision = revision + 1,
      updated_by = p_actor, updated_at = server_timestamp
    where schedule_id = p_schedule_id and status = 'planned';
  else
    insert into public.atlas_cycle_schedules (
      id, business, enabled, duration_weeks, cooldown_days, future_cycles,
      start_date, timezone, auto_rollover, auto_add_started, created_by, updated_by
    ) values (
      p_schedule_id, p_business, true, p_duration_weeks, p_cooldown_days,
      p_future_cycles, p_start_date, coalesce(nullif(p_timezone, ''), 'America/Los_Angeles'),
      p_auto_rollover, p_auto_add_started, p_actor, p_actor
    ) returning * into schedule_row;
  end if;

  select * into active_row from public.atlas_cycles
   where schedule_id = p_schedule_id and status = 'active'
   order by start_date desc limit 1 for update;
  select coalesce(max(cycle_number), 0) + 1 into next_number
    from public.atlas_cycles where schedule_id = p_schedule_id;

  if active_row.id is not null then
    next_start := active_row.end_date + schedule_row.cooldown_days + 1;
  else
    next_start := p_start_date;
    while next_start + (p_duration_weeks * 7 - 1) < current_date loop
      next_end := next_start + (p_duration_weeks * 7 - 1);
      insert into public.atlas_cycles (
        id, schedule_id, cycle_number, name, start_date, end_date, status,
        scope_effort_snapshot, started_effort_snapshot, completed_effort_snapshot,
        success_percent_snapshot, action_snapshot, completed_at, created_by, updated_by
      ) values (
        gen_random_uuid()::text, p_schedule_id, next_number, format('Cycle %s', next_number),
        next_start, next_end, 'completed', 0, 0, 0, 0, '[]'::jsonb,
        server_timestamp, p_actor, p_actor
      ) returning * into cycle_row;
      generated := generated || to_jsonb(cycle_row);
      next_number := next_number + 1;
      next_start := next_end + p_cooldown_days + 1;
    end loop;
  end if;

  for index_value in 0..(case when active_row.id is not null then p_future_cycles - 1 else p_future_cycles end) loop
    next_end := next_start + (p_duration_weeks * 7 - 1);
    cycle_status := case when current_date between next_start and next_end then 'active' else 'planned' end;
    insert into public.atlas_cycles (
      id, schedule_id, cycle_number, name, start_date, end_date, status,
      created_by, updated_by
    ) values (
      gen_random_uuid()::text, p_schedule_id, next_number, format('Cycle %s', next_number),
      next_start, next_end, cycle_status, p_actor, p_actor
    ) returning * into cycle_row;
    generated := generated || to_jsonb(cycle_row);
    next_number := next_number + 1;
    next_start := next_end + p_cooldown_days + 1;
  end loop;

  return jsonb_build_object('schedule', to_jsonb(schedule_row), 'cycles', generated);
end
$function$;

create or replace function public.assign_atlas_action_to_cycle(
  p_cycle_id text,
  p_action_id text,
  p_actor text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  cycle_row public.atlas_cycles%rowtype;
  action_row public.atlas_actions%rowtype;
  old_cycle_id text;
  schedule_business text;
begin
  if p_actor not in ('ransomed', 'codex', 'claude') then raise exception using errcode = '22023', message = 'ATLAS_ACTOR_NOT_ALLOWED'; end if;
  select * into cycle_row from public.atlas_cycles where id = p_cycle_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_CYCLE_NOT_FOUND'; end if;
  if cycle_row.status not in ('planned', 'active') then raise exception using errcode = '55000', message = 'ATLAS_CYCLE_NOT_ASSIGNABLE'; end if;
  select * into action_row from public.atlas_actions where id = p_action_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_ACTION_NOT_FOUND'; end if;
  if action_row.status = 'archived' then raise exception using errcode = '55000', message = 'ATLAS_ACTION_ARCHIVED'; end if;
  select business into schedule_business from public.atlas_cycle_schedules where id = cycle_row.schedule_id;
  if schedule_business is not null and action_row.business is distinct from schedule_business then
    raise exception using errcode = '23514', message = 'ATLAS_CYCLE_ACTION_BUSINESS_MISMATCH';
  end if;
  old_cycle_id := action_row.cycle_id;
  update public.atlas_actions set cycle_id = p_cycle_id, updated_at = timezone('utc', now())
   where id = p_action_id returning * into action_row;
  insert into public.atlas_activity_log (action_id, event, old_value, new_value, actor)
  values (p_action_id, 'cycle_assigned', old_cycle_id, p_cycle_id, p_actor);
  insert into public.atlas_cycle_activity_log (cycle_id, schedule_id, event, old_value, new_value, actor)
  values (p_cycle_id, cycle_row.schedule_id, 'action_assigned', jsonb_build_object('cycle_id', old_cycle_id), jsonb_build_object('action_id', p_action_id), p_actor);
  return to_jsonb(action_row);
end
$function$;

