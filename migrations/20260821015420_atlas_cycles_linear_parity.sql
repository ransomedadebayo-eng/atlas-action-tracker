create or replace function public.complete_atlas_cycle(
  p_cycle_id text,
  p_actor text,
  p_expected_revision bigint default null,
  p_start_next_now boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  cycle_row public.atlas_cycles%rowtype;
  next_cycle public.atlas_cycles%rowtype;
  schedule_row public.atlas_cycle_schedules%rowtype;
  unestimated_value integer := 1;
  scope_effort integer;
  started_effort integer;
  completed_effort integer;
  success_percent numeric(6,2);
  snapshot jsonb;
  rolled_count integer := 0;
  server_timestamp timestamptz := timezone('utc', now());
begin
  if p_actor <> 'ransomed' then raise exception using errcode = '42501', message = 'ATLAS_OWNER_REQUIRED'; end if;
  select * into cycle_row from public.atlas_cycles where id = p_cycle_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_CYCLE_NOT_FOUND'; end if;
  if cycle_row.status <> 'active' then raise exception using errcode = '22023', message = 'ATLAS_CYCLE_NOT_ACTIVE'; end if;
  if p_expected_revision is not null and cycle_row.revision <> p_expected_revision then raise exception using errcode = '40001', message = 'ATLAS_CYCLE_REVISION_CONFLICT'; end if;
  select * into schedule_row from public.atlas_cycle_schedules where id = cycle_row.schedule_id for update;
  select coalesce((value->>'unestimated_value')::integer, 1) into unestimated_value
    from public.atlas_config where key = 'estimate_settings';
  unestimated_value := coalesce(unestimated_value, 1);

  select
    coalesce(sum(coalesce(estimate_points, unestimated_value)), 0)::integer,
    coalesce(sum(case when status in ('in_progress', 'waiting', 'blocked') then coalesce(estimate_points, unestimated_value) else 0 end), 0)::integer,
    coalesce(sum(case when status in ('done', 'completed', 'closed') then coalesce(estimate_points, unestimated_value) else 0 end), 0)::integer,
    coalesce(jsonb_agg(jsonb_build_object('id', id, 'status', status, 'estimate_points', estimate_points) order by id), '[]'::jsonb)
  into scope_effort, started_effort, completed_effort, snapshot
  from public.atlas_actions where cycle_id = p_cycle_id;
  success_percent := case when scope_effort = 0 then 0 else round(((completed_effort + started_effort * 0.25) / scope_effort::numeric) * 100, 2) end;

  select * into next_cycle from public.atlas_cycles
   where schedule_id = cycle_row.schedule_id and status = 'planned'
   order by start_date asc limit 1 for update;
  if next_cycle.id is null then
    insert into public.atlas_cycles (id, schedule_id, cycle_number, name, start_date, end_date, status, created_by, updated_by)
    values (
      gen_random_uuid()::text, cycle_row.schedule_id, cycle_row.cycle_number + 1,
      format('Cycle %s', cycle_row.cycle_number + 1),
      cycle_row.end_date + schedule_row.cooldown_days + 1,
      cycle_row.end_date + schedule_row.cooldown_days + schedule_row.duration_weeks * 7,
      'planned', p_actor, p_actor
    ) returning * into next_cycle;
  end if;

  update public.atlas_cycles set status = 'completed',
    scope_effort_snapshot = scope_effort, started_effort_snapshot = started_effort,
    completed_effort_snapshot = completed_effort, success_percent_snapshot = success_percent,
    action_snapshot = snapshot, completed_at = server_timestamp,
    revision = revision + 1, updated_by = p_actor, updated_at = server_timestamp
  where id = p_cycle_id returning * into cycle_row;

  if p_start_next_now then
    update public.atlas_cycles set start_date = current_date,
      end_date = current_date + (schedule_row.duration_weeks * 7 - 1),
      status = 'active', revision = revision + 1, updated_by = p_actor, updated_at = server_timestamp
    where id = next_cycle.id returning * into next_cycle;
    with future as (
      select id, row_number() over (order by cycle_number)::integer as position
      from public.atlas_cycles
      where schedule_id = cycle_row.schedule_id and status = 'planned' and id <> next_cycle.id
    )
    update public.atlas_cycles cycle
       set start_date = next_cycle.end_date + schedule_row.cooldown_days + 1
           + ((future.position - 1) * (schedule_row.duration_weeks * 7 + schedule_row.cooldown_days)),
           end_date = next_cycle.end_date + schedule_row.cooldown_days
           + ((future.position - 1) * (schedule_row.duration_weeks * 7 + schedule_row.cooldown_days))
           + schedule_row.duration_weeks * 7,
           revision = cycle.revision + 1,
           updated_by = p_actor,
           updated_at = server_timestamp
      from future
     where cycle.id = future.id;
  elsif next_cycle.start_date <= current_date then
    update public.atlas_cycles set status = 'active', revision = revision + 1,
      updated_by = p_actor, updated_at = server_timestamp
    where id = next_cycle.id returning * into next_cycle;
  end if;

  if schedule_row.auto_rollover then
    update public.atlas_actions set cycle_id = next_cycle.id, updated_at = server_timestamp
     where cycle_id = p_cycle_id
       and status in ('not_started', 'in_progress', 'waiting', 'blocked', 'todo', 'open');
    get diagnostics rolled_count = row_count;
  end if;
  insert into public.atlas_cycle_activity_log (cycle_id, schedule_id, event, old_value, new_value, actor)
  values (
    p_cycle_id, cycle_row.schedule_id, 'cycle_rollover_completed', null,
    jsonb_build_object('next_cycle_id', next_cycle.id, 'rolled_actions', rolled_count, 'success_percent', success_percent), p_actor
  );
  return jsonb_build_object('cycle', to_jsonb(cycle_row), 'next_cycle', to_jsonb(next_cycle), 'rolled_actions', rolled_count);
end
$function$;

create or replace function public.disable_atlas_cycle_schedule(
  p_schedule_id text,
  p_actor text,
  p_expected_revision bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  schedule_row public.atlas_cycle_schedules%rowtype;
  cycle_row public.atlas_cycles%rowtype;
  unestimated_value integer := 1;
  scope_effort integer;
  started_effort integer;
  completed_effort integer;
  success_percent numeric(6,2);
  snapshot jsonb;
  server_timestamp timestamptz := timezone('utc', now());
begin
  if p_actor <> 'ransomed' then raise exception using errcode = '42501', message = 'ATLAS_OWNER_REQUIRED'; end if;
  select * into schedule_row from public.atlas_cycle_schedules where id = p_schedule_id for update;
  if not found then raise exception using errcode = 'P0002', message = 'ATLAS_CYCLE_SCHEDULE_NOT_FOUND'; end if;
  if p_expected_revision is not null and schedule_row.revision <> p_expected_revision then raise exception using errcode = '40001', message = 'ATLAS_CYCLE_REVISION_CONFLICT'; end if;
  select * into cycle_row from public.atlas_cycles where schedule_id = p_schedule_id and status = 'active' order by start_date desc limit 1 for update;
  if cycle_row.id is not null then
    select coalesce((value->>'unestimated_value')::integer, 1) into unestimated_value from public.atlas_config where key = 'estimate_settings';
    unestimated_value := coalesce(unestimated_value, 1);
    select
      coalesce(sum(coalesce(estimate_points, unestimated_value)), 0)::integer,
      coalesce(sum(case when status in ('in_progress','waiting','blocked') then coalesce(estimate_points, unestimated_value) else 0 end), 0)::integer,
      coalesce(sum(case when status in ('done','completed','closed') then coalesce(estimate_points, unestimated_value) else 0 end), 0)::integer,
      coalesce(jsonb_agg(jsonb_build_object('id',id,'status',status,'estimate_points',estimate_points) order by id), '[]'::jsonb)
    into scope_effort, started_effort, completed_effort, snapshot
    from public.atlas_actions where cycle_id = cycle_row.id;
    success_percent := case when scope_effort = 0 then 0 else round(((completed_effort + started_effort * 0.25) / scope_effort::numeric) * 100, 2) end;
    update public.atlas_cycles set status = 'completed', scope_effort_snapshot = scope_effort,
      started_effort_snapshot = started_effort, completed_effort_snapshot = completed_effort,
      success_percent_snapshot = success_percent, action_snapshot = snapshot,
      completed_at = server_timestamp, revision = revision + 1,
      updated_by = p_actor, updated_at = server_timestamp
    where id = cycle_row.id returning * into cycle_row;
  end if;
  update public.atlas_cycles set status = 'archived', revision = revision + 1,
    updated_by = p_actor, updated_at = server_timestamp
  where schedule_id = p_schedule_id and status = 'planned';
  update public.atlas_cycle_schedules set enabled = false, revision = revision + 1,
    updated_by = p_actor, updated_at = server_timestamp
  where id = p_schedule_id returning * into schedule_row;
  return jsonb_build_object('schedule', to_jsonb(schedule_row), 'completed_cycle', case when cycle_row.id is null then null else to_jsonb(cycle_row) end);
end
$function$;

create or replace function public.atlas_auto_add_action_to_cycle()
returns trigger
language plpgsql
set search_path = ''
as $function$
declare
  target_cycle_id text;
begin
  if new.cycle_id is not null or new.status not in ('in_progress', 'waiting', 'blocked', 'done', 'completed', 'closed') then return new; end if;
  select cycle.id into target_cycle_id
    from public.atlas_cycles cycle
    join public.atlas_cycle_schedules schedule on schedule.id = cycle.schedule_id
   where schedule.enabled and schedule.auto_add_started and cycle.status = 'active'
     and (schedule.business = new.business or schedule.business is null)
   order by (schedule.business = new.business) desc, cycle.start_date desc
   limit 1;
  if target_cycle_id is null and new.status in ('done', 'completed', 'closed') then
    select cycle.id into target_cycle_id
      from public.atlas_cycles cycle
      join public.atlas_cycle_schedules schedule on schedule.id = cycle.schedule_id
     where schedule.enabled and schedule.auto_add_started and cycle.status = 'completed'
       and (schedule.business = new.business or schedule.business is null)
       and current_date <= cycle.end_date + schedule.cooldown_days
     order by cycle.end_date desc limit 1;
  end if;
  if target_cycle_id is not null then
    update public.atlas_actions set cycle_id = target_cycle_id, updated_at = timezone('utc', now()) where id = new.id;
  end if;
  return new;
end
$function$;

