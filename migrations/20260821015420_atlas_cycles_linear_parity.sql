create or replace function public.atlas_protect_completed_cycle_snapshot()
returns trigger
language plpgsql
set search_path = ''
as $function$
begin
  if old.status = 'completed' and (
    new.schedule_id is distinct from old.schedule_id
    or new.cycle_number is distinct from old.cycle_number
    or new.start_date is distinct from old.start_date
    or new.end_date is distinct from old.end_date
    or new.scope_effort_snapshot is distinct from old.scope_effort_snapshot
    or new.started_effort_snapshot is distinct from old.started_effort_snapshot
    or new.completed_effort_snapshot is distinct from old.completed_effort_snapshot
    or new.success_percent_snapshot is distinct from old.success_percent_snapshot
    or new.action_snapshot is distinct from old.action_snapshot
    or new.completed_at is distinct from old.completed_at
  ) then
    raise exception using errcode = '55000', message = 'ATLAS_CYCLE_SNAPSHOT_IMMUTABLE';
  end if;
  return new;
end
$function$;

