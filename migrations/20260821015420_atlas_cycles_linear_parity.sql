-- Linear parity slice 3: repeating ATLAS cycles, capacity, live scope events,
-- immutable completion snapshots, action assignment, and rollover.

create table if not exists public.atlas_cycle_schedules (
  id text primary key,
  business text,
  enabled boolean not null default true,
  duration_weeks integer not null default 2 check (duration_weeks between 1 and 8),
  cooldown_days integer not null default 0 check (cooldown_days in (0, 7, 14)),
  future_cycles integer not null default 3 check (future_cycles between 1 and 15),
  start_date date not null,
  timezone text not null default 'America/Los_Angeles',
  auto_rollover boolean not null default true,
  auto_add_started boolean not null default false,
  revision bigint not null default 0 check (revision >= 0),
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create unique index if not exists atlas_cycle_schedules_business_idx
  on public.atlas_cycle_schedules (coalesce(business, '__workspace__'))
  where enabled;

create table if not exists public.atlas_cycles (
  id text primary key,
  schedule_id text not null references public.atlas_cycle_schedules(id) on delete restrict,
  cycle_number integer not null check (cycle_number > 0),
  name text not null,
  start_date date not null,
  end_date date not null,
  status text not null default 'planned'
    check (status in ('planned', 'active', 'completed', 'archived')),
  capacity_override integer check (capacity_override is null or capacity_override >= 0),
  scope_effort_snapshot integer,
  started_effort_snapshot integer,
  completed_effort_snapshot integer,
  success_percent_snapshot numeric(6,2),
  action_snapshot jsonb,
  completed_at timestamptz,
  revision bigint not null default 0 check (revision >= 0),
  created_by text not null,
  updated_by text not null,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now()),
  unique (schedule_id, cycle_number),
  check (start_date <= end_date),
  check (
    status <> 'completed'
    or (scope_effort_snapshot is not null and completed_effort_snapshot is not null and success_percent_snapshot is not null and action_snapshot is not null and completed_at is not null)
  )
);

create index if not exists atlas_cycles_schedule_status_dates_idx
  on public.atlas_cycles (schedule_id, status, start_date, end_date);
create unique index if not exists atlas_cycles_one_active_schedule_idx
  on public.atlas_cycles (schedule_id)
  where status = 'active';

create table if not exists public.atlas_cycle_scope_events (
  id bigint generated by default as identity primary key,
  cycle_id text not null references public.atlas_cycles(id) on delete restrict,
  event_type text not null,
  action_id text,
  scope_effort integer not null,
  started_effort integer not null,
  completed_effort integer not null,
  issue_count integer not null,
  completed_count integer not null,
  actor text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists atlas_cycle_scope_events_cycle_created_idx
  on public.atlas_cycle_scope_events (cycle_id, created_at, id);

create table if not exists public.atlas_cycle_activity_log (
  id bigint generated by default as identity primary key,
  cycle_id text,
  schedule_id text,
  event text not null,
  old_value jsonb,
  new_value jsonb,
  actor text not null,
  created_at timestamptz not null default timezone('utc', now()),
  check (cycle_id is not null or schedule_id is not null)
